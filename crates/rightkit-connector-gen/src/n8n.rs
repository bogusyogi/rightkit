//! n8n community node: a declarative-style node whose operations post to the app's HTTP bridge.

use crate::{
    camel_method, json_string, pascal, rpc_path, Contract, GenError, GeneratedFile, Operation,
    Param, ParamType,
};

fn n8n_type(ty: ParamType) -> &'static str {
    match ty {
        ParamType::String => "string",
        ParamType::Number => "number",
        ParamType::Boolean => "boolean",
        ParamType::Json => "json",
    }
}

fn n8n_default(ty: ParamType) -> &'static str {
    match ty {
        ParamType::String => "''",
        ParamType::Number => "0",
        ParamType::Boolean => "false",
        ParamType::Json => "'{}'",
    }
}

fn param_block(op: &Operation, p: &Param) -> String {
    let mut s = String::new();
    s.push_str("      {\n");
    s.push_str(&format!(
        "        displayName: {},\n        name: {},\n        type: '{}',\n        required: {},\n        default: {},\n        description: {},\n",
        json_string(&pascal(&p.name)),
        json_string(&format!("{}_{}", camel_method(&op.method), p.name)),
        n8n_type(p.ty),
        p.required,
        n8n_default(p.ty),
        json_string(&p.description),
    ));
    s.push_str(&format!(
        "        displayOptions: {{ show: {{ operation: [{}] }} }},\n",
        json_string(&op.method)
    ));
    s.push_str(&format!(
        "        routing: {{ send: {{ type: 'body', property: {} }} }},\n",
        json_string(&p.name)
    ));
    s.push_str("      },\n");
    s
}

fn operation_option(op: &Operation) -> String {
    format!(
        "          {{\n            name: {name},\n            value: {value},\n            action: {name},\n            description: {desc},\n            routing: {{ request: {{ method: 'POST', url: {url} }} }},\n          }},\n",
        name = json_string(&op.method),
        value = json_string(&op.method),
        desc = json_string(&op.summary),
        url = json_string(&rpc_path(&op.method)),
    )
}

/// Render the node package. Paths are relative to the package root.
pub fn render(contract: &Contract) -> Result<Vec<GeneratedFile>, GenError> {
    contract.validate()?;
    let name = contract.pascal_name();
    let lower_first = {
        let mut c = name.chars();
        match c.next() {
            Some(f) => f.to_ascii_lowercase().to_string() + c.as_str(),
            None => String::new(),
        }
    };
    let cred_name = format!("{lower_first}Api");
    let cred_class = format!("{name}Api");

    let mut node = String::new();
    node.push_str(
        "// Generated by rightkit-connector-gen from the engine contract. Do not edit by hand.\n",
    );
    node.push_str("import type { INodeType, INodeTypeDescription } from 'n8n-workflow';\n\n");
    node.push_str(&format!("export class {name} implements INodeType {{\n"));
    node.push_str("  description: INodeTypeDescription = {\n");
    node.push_str(&format!("    displayName: {},\n", json_string(&name)));
    node.push_str(&format!("    name: {},\n", json_string(&lower_first)));
    node.push_str("    group: ['transform'],\n    version: 1,\n");
    node.push_str("    subtitle: '={{$parameter[\"operation\"]}}',\n");
    node.push_str(&format!(
        "    description: {},\n",
        json_string(&format!(
            "Call {name} engine methods ({} operations)",
            contract.operations.len()
        ))
    ));
    node.push_str(&format!(
        "    defaults: {{ name: {} }},\n",
        json_string(&name)
    ));
    node.push_str("    inputs: ['main'],\n    outputs: ['main'],\n");
    node.push_str(&format!(
        "    credentials: [{{ name: {}, required: true }}],\n",
        json_string(&cred_name)
    ));
    node.push_str("    requestDefaults: {\n      baseURL: '={{$credentials.baseUrl}}',\n      headers: { Accept: 'application/json', 'Content-Type': 'application/json' },\n    },\n");
    node.push_str("    properties: [\n");
    if contract.operations.is_empty() {
        node.push_str("      // The contract lists no operations.\n");
    } else {
        node.push_str("      {\n        displayName: 'Operation',\n        name: 'operation',\n        type: 'options',\n        noDataExpression: true,\n        options: [\n");
        for op in &contract.operations {
            node.push_str(&operation_option(op));
        }
        node.push_str("        ],\n");
        node.push_str(&format!(
            "        default: {},\n      }},\n",
            json_string(&contract.operations[0].method)
        ));
        for op in &contract.operations {
            for p in &op.params {
                node.push_str(&param_block(op, p));
            }
        }
    }
    node.push_str("    ],\n  };\n}\n");

    let cred = format!(
        "// Generated by rightkit-connector-gen from the engine contract. Do not edit by hand.\nimport type {{ IAuthenticateGeneric, ICredentialType, INodeProperties }} from 'n8n-workflow';\n\nexport class {cred_class} implements ICredentialType {{\n  name = {cred_name_lit};\n  displayName = {display};\n  properties: INodeProperties[] = [\n    {{ displayName: 'Base URL', name: 'baseUrl', type: 'string', default: '' }},\n    {{ displayName: 'Token', name: 'token', type: 'string', typeOptions: {{ password: true }}, default: '' }},\n  ];\n  authenticate: IAuthenticateGeneric = {{\n    type: 'generic',\n    properties: {{ headers: {{ Authorization: '=Bearer {{{{$credentials.token}}}}' }} }},\n  }};\n}}\n",
        cred_class = cred_class,
        cred_name_lit = json_string(&cred_name),
        display = json_string(&format!("{name} API")),
    );

    let package = format!(
        "{{\n  \"name\": {pkg},\n  \"version\": {version},\n  \"description\": {desc},\n  \"keywords\": [\"n8n-community-node-package\"],\n  \"license\": \"MIT\",\n  \"files\": [\"dist\"],\n  \"scripts\": {{ \"build\": \"tsc\" }},\n  \"n8n\": {{\n    \"n8nNodesApiVersion\": 1,\n    \"credentials\": [{cred_path}],\n    \"nodes\": [{node_path}]\n  }},\n  \"devDependencies\": {{ \"typescript\": \"^5.6.0\", \"n8n-workflow\": \"*\" }},\n  \"peerDependencies\": {{ \"n8n-workflow\": \"*\" }}\n}}\n",
        pkg = json_string(&format!("n8n-nodes-{}", contract.slug())),
        version = json_string(&contract.version),
        desc = json_string(&format!("n8n node for {name}, generated from its engine contract")),
        cred_path = json_string(&format!("dist/credentials/{cred_class}.credentials.js")),
        node_path = json_string(&format!("dist/nodes/{name}/{name}.node.js")),
    );

    let tsconfig = "{\n  \"compilerOptions\": {\n    \"target\": \"es2019\",\n    \"module\": \"commonjs\",\n    \"strict\": true,\n    \"outDir\": \"dist\",\n    \"skipLibCheck\": true\n  },\n  \"include\": [\"credentials/**/*\", \"nodes/**/*\"]\n}\n";

    Ok(vec![
        GeneratedFile {
            path: "package.json".into(),
            contents: package,
        },
        GeneratedFile {
            path: "tsconfig.json".into(),
            contents: tsconfig.into(),
        },
        GeneratedFile {
            path: format!("credentials/{cred_class}.credentials.ts"),
            contents: cred,
        },
        GeneratedFile {
            path: format!("nodes/{name}/{name}.node.ts"),
            contents: node,
        },
    ])
}
