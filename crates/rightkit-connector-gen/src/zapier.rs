//! Zapier CLI app: one create action per engine method, posting to the app's HTTP bridge.

use crate::{json_string, rpc_path, Contract, GenError, GeneratedFile, Operation, ParamType};

fn zapier_type(ty: ParamType) -> &'static str {
    match ty {
        ParamType::String => "string",
        ParamType::Number => "number",
        ParamType::Boolean => "boolean",
        ParamType::Json => "text",
    }
}

fn spec_type(ty: ParamType) -> &'static str {
    match ty {
        ParamType::Json => "json",
        _ => "plain",
    }
}

/// A Zapier action key: lower case, underscores.
fn action_key(method: &str) -> String {
    method
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn operation_source(op: &Operation) -> String {
    let mut fields = String::new();
    let mut spec = String::new();
    for p in &op.params {
        fields.push_str(&format!(
            "      {{ key: {}, label: {}, type: {}, required: {}, helpText: {} }},\n",
            json_string(&p.name),
            json_string(&p.name),
            json_string(zapier_type(p.ty)),
            p.required,
            json_string(&p.description),
        ));
        spec.push_str(&format!(
            "[{}, {}], ",
            json_string(&p.name),
            json_string(spec_type(p.ty))
        ));
    }
    format!(
        "  [{key}]: {{\n    key: {key},\n    noun: {noun},\n    display: {{ label: {noun}, description: {desc} }},\n    operation: {{\n      inputFields: [\n{fields}      ],\n      perform: async (z, bundle) => {{\n        const response = await z.request({{\n          method: 'POST',\n          url: bundle.authData.baseUrl + {url},\n          body: buildBody(bundle.inputData, [{spec}]),\n        }});\n        return response.data;\n      }},\n    }},\n  }},\n",
        key = json_string(&action_key(&op.method)),
        noun = json_string(&op.method),
        desc = json_string(&op.summary),
        url = json_string(&rpc_path(&op.method)),
        fields = fields,
        spec = spec.trim_end_matches([',', ' ']),
    )
}

/// Render the app. Paths are relative to the app root.
pub fn render(contract: &Contract) -> Result<Vec<GeneratedFile>, GenError> {
    contract.validate()?;
    let mut index = String::new();
    index.push_str(
        "// Generated by rightkit-connector-gen from the engine contract. Do not edit by hand.\n",
    );
    index.push_str("const zapier = require('zapier-platform-core');\nconst { version } = require('./package.json');\n\n");
    index.push_str("// Params the user left empty are not sent; JSON params arrive as text and are parsed.\nfunction buildBody(input, spec) {\n  const body = {};\n  for (const [key, type] of spec) {\n    const value = input[key];\n    if (value === undefined || value === null || value === '') continue;\n    body[key] = type === 'json' && typeof value === 'string' ? JSON.parse(value) : value;\n  }\n  return body;\n}\n\n");
    index.push_str("const addAuthHeader = (request, z, bundle) => {\n  request.headers = request.headers || {};\n  request.headers.Authorization = 'Bearer ' + bundle.authData.token;\n  return request;\n};\n\n");
    index.push_str("const authentication = {\n  type: 'custom',\n  fields: [\n    { key: 'baseUrl', label: 'Base URL', required: true, type: 'string' },\n    { key: 'token', label: 'Token', required: true, type: 'password' },\n  ],\n  // The engine's built-in doctor method answers when the bridge, URL and token are right.\n  test: async (z, bundle) => {\n    const response = await z.request({ method: 'POST', url: bundle.authData.baseUrl + '/rpc/doctor', body: {} });\n    return response.data;\n  },\n};\n\n");
    index.push_str("const creates = {\n");
    for op in &contract.operations {
        index.push_str(&operation_source(op));
    }
    index.push_str("};\n\n");
    index.push_str("module.exports = {\n  version,\n  platformVersion: zapier.version,\n  authentication,\n  beforeRequest: [addAuthHeader],\n  creates,\n};\n");

    let package = format!(
        "{{\n  \"name\": {pkg},\n  \"version\": {version},\n  \"description\": {desc},\n  \"main\": \"index.js\",\n  \"license\": \"MIT\",\n  \"private\": true,\n  \"dependencies\": {{ \"zapier-platform-core\": \"*\" }}\n}}\n",
        pkg = json_string(&format!("{}-zapier", contract.slug())),
        version = json_string(&contract.version),
        desc = json_string(&format!(
            "Zapier app for {}, generated from its engine contract",
            contract.pascal_name()
        )),
    );

    Ok(vec![
        GeneratedFile {
            path: "package.json".into(),
            contents: package,
        },
        GeneratedFile {
            path: "index.js".into(),
            contents: index,
        },
    ])
}
