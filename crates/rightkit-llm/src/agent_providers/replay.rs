fn stored_error_to_provider(e: &StoredError) -> ProviderError {
    match e.kind.as_str() {
        "auth" => ProviderError::Auth,
        "rate_limited" => ProviderError::RateLimited {
            retry_after_secs: e.retry_after_secs.unwrap_or(5),
        },
        "http" => ProviderError::Http {
            status: e.status.unwrap_or(500),
            body: e
                .body
                .clone()
                .unwrap_or_else(|| e.message.clone().unwrap_or_default()),
        },
        "sse" => ProviderError::Sse(
            e.body
                .clone()
                .unwrap_or_else(|| e.message.clone().unwrap_or_default()),
        ),
        "network" => ProviderError::Network(
            e.message
                .clone()
                .unwrap_or_else(|| e.body.clone().unwrap_or_default()),
        ),
        "provider" => ProviderError::Provider(
            e.message
                .clone()
                .unwrap_or_else(|| e.body.clone().unwrap_or_default()),
        ),
        _ => ProviderError::Provider(
            e.message
                .clone()
                .unwrap_or_else(|| format!("unknown kind {}", e.kind)),
        ),
    }
}

