/// Record when `RIGHTKIT_RECORD_REPLAY=1`; otherwise a no-op. Errors are
/// logged to stderr but do not fail the caller — recording must never break
/// live traffic.
pub fn maybe_record_deltas(scenario: &str, deltas: &[CompletionDelta]) -> bool {
    if !is_record_mode() {
        return false;
    }
    match record_deltas(scenario, deltas, None, None) {
        Ok(_) => {
            eprintln!(
                "recorded replay corpus '{scenario}' ({} deltas) to {}",
                deltas.len(),
                corpus_path(scenario).display()
            );
            true
        }
        Err(e) => {
            eprintln!("WARN: failed to record replay corpus '{scenario}': {e}");
            false
        }
    }
}

pub fn maybe_record_turn(scenario: &str, turn: &CompletedTurn) -> bool {
    if !is_record_mode() {
        return false;
    }
    // Synthesize a delta script from the turn for recording.
    let deltas = turn_to_deltas(turn);
    maybe_record_deltas(scenario, &deltas)
}

fn turn_to_deltas(turn: &CompletedTurn) -> Vec<CompletionDelta> {
    let mut out = Vec::new();
    if !turn.text.is_empty() {
        out.push(CompletionDelta {
            index: 0,
            id: Some("chatcmpl-recorded".into()),
            role: Some("assistant".into()),
            content: Some(turn.text.clone()),
            reasoning_content: turn.reasoning.clone(),
            tool_call_name: None,
            tool_call_arguments_fragment: None,
            finish_reason: turn.finish_reason.clone(),
        });
    }
    for (i, tc) in turn.tool_calls.iter().enumerate() {
        out.push(CompletionDelta {
            index: i,
            id: Some(tc.id.clone()),
            role: Some("assistant".into()),
            content: None,
            reasoning_content: None,
            tool_call_name: Some(tc.name.clone()),
            tool_call_arguments_fragment: Some(tc.arguments_json.clone()),
            finish_reason: None,
        });
    }
    if out.is_empty() {
        out.push(CompletionDelta {
            index: 0,
            id: Some("chatcmpl-recorded".into()),
            role: Some("assistant".into()),
            content: Some(String::new()),
            reasoning_content: None,
            tool_call_name: None,
            tool_call_arguments_fragment: None,
            finish_reason: Some("stop".into()),
        });
    }
    out
}

