// ── Corpus constants ──────────────────────────────────────────────────────────

/// Current on-disk schema version. Bump when `CompletionDelta` or header shape
/// changes; loaders reject any other version so stale fixtures cannot hide
/// drift.
pub const CORPUS_VERSION: u32 = 1;

/// Maximum age of a recorded fixture before it is considered stale.
pub const CORPUS_MAX_AGE_DAYS: u64 = 90;
pub const CORPUS_MAX_AGE_SECS: u64 = CORPUS_MAX_AGE_DAYS * 24 * 3600;

/// Env var that enables live capture. Mirrors the contract value
/// `RIGHTKIT_RECORD_REPLAY=1`.
#[cfg(any(test, feature = "agent_providers-replay-record"))]
pub const CORPUS_ENV_RECORD: &str = "RIGHTKIT_RECORD_REPLAY";
/// Shipped builds (desktop and mobile) never record a replay corpus, so they carry no switch name.
#[cfg(not(any(test, feature = "agent_providers-replay-record")))]
pub const CORPUS_ENV_RECORD: &str = "the QA replay-record switch";
/// Optional override for the corpus directory (useful in tests).
pub const CORPUS_ENV_DIR_OVERRIDE: &str = "RIGHTKIT_REPLAY_CORPUS_DIR";

/// Required named scenarios — every one must have a `*.jsonl` corpus file.
pub const REQUIRED_SCENARIOS: &[&str] = &[
    "short_text_reply",
    "single_tool_call",
    "malformed_midstream",
    "cancel_midstream",
    "auth_failure",
    "rate_limit",
    "context_overflow",
    "retry_then_succeed",
    "policy_exhausted",
    "two_turns",
];

/// The three explicitly required error cases from the contract.
pub const NAMED_ERROR_SCENARIOS: &[&str] = &["auth_failure", "rate_limit", "context_overflow"];

const REDACTED: &str = "[REDACTED]";

// ── Header & errors ───────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CorpusHeader {
    pub version: u32,
    pub scenario: String,
    pub recorded_at: String,
    pub redacted: bool,
    #[serde(default)]
    pub provider: Option<String>,
    #[serde(default)]
    pub model: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StoredError {
    kind: String,
    #[serde(default)]
    status: Option<u16>,
    #[serde(default)]
    body: Option<String>,
    #[serde(default)]
    retry_after_secs: Option<u64>,
    #[serde(default)]
    message: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct CorpusErrorLine {
    error: StoredError,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct StoredFailoverEvent {
    from: String,
    to: String,
    reason: String,
    breaker_skipped: bool,
}

#[derive(Debug, thiserror::Error)]
pub enum CorpusError {
    #[error("corpus io error at {path}: {source}")]
    Io {
        path: String,
        source: std::io::Error,
    },
    #[error("corpus json error at {path}: {source}")]
    Json {
        path: String,
        source: serde_json::Error,
    },
    #[error("missing corpus file for scenario '{scenario}' at {path}")]
    Missing { scenario: String, path: String },
    #[error("corpus version mismatch for '{scenario}': expected {expected}, got {got} at {path}")]
    VersionMismatch {
        scenario: String,
        expected: u32,
        got: u32,
        path: String,
    },
    #[error("corpus for '{scenario}' is not marked redacted at {path}")]
    NotRedacted { scenario: String, path: String },
    #[error("corpus for '{scenario}' is stale: recorded_at={recorded_at} age {age_secs}s > {max_age_secs}s at {path}")]
    Stale {
        scenario: String,
        recorded_at: String,
        age_secs: u64,
        max_age_secs: u64,
        path: String,
    },
    #[error("corpus header timestamp unparseable for '{scenario}': {recorded_at} at {path}")]
    UnparseableTimestamp {
        scenario: String,
        recorded_at: String,
        path: String,
    },
}

// ── Time helpers (`rightkit-time`) ────────────────────────────────────────────

/// RFC 3339 UTC text (`YYYY-MM-DDTHH:MM:SSZ`) for `secs` since the Unix epoch.
fn epoch_to_iso(secs: u64) -> String {
    i64::try_from(secs)
        .ok()
        .and_then(|secs| rightkit_time::DateTime::from_unix(secs, 0))
        .map(|dt| dt.format_rfc3339())
        .unwrap_or_default()
}

/// Seconds since the Unix epoch for a corpus timestamp: a plain integer string,
/// or RFC 3339 (`Z` or a numeric offset, optional fractional seconds). `None`
/// for anything else; the caller then tries the file-mtime fallback.
fn iso_to_epoch(s: &str) -> Option<u64> {
    let s = s.trim();
    if s.is_empty() {
        return None;
    }
    if let Ok(v) = s.parse::<u64>() {
        return Some(v);
    }
    let parsed = rightkit_time::DateTime::parse_rfc3339(s)?;
    u64::try_from(parsed.unix_seconds()).ok()
}

fn now_epoch_secs() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
}

// ── Corpus directory resolution ──────────────────────────────────────────────

/// True when `RIGHTKIT_RECORD_REPLAY=1` (or `true`/`yes`/`on`). Test and QA builds only
/// (`replay-record`): a shipped desktop build never writes provider traffic to disk.
#[cfg(any(test, feature = "agent_providers-replay-record"))]
pub fn is_record_mode() -> bool {
    std::env::var(CORPUS_ENV_RECORD)
        .map(|v| {
            let t = v.trim().to_ascii_lowercase();
            t == "1" || t == "true" || t == "yes" || t == "on"
        })
        .unwrap_or(false)
}

/// Record mode is a test / QA (`replay-record`) capability only.
#[cfg(not(any(test, feature = "agent_providers-replay-record")))]
pub fn is_record_mode() -> bool {
    false
}

/// Resolve the corpus directory. Priority:
/// 1. `$RIGHTKIT_REPLAY_CORPUS_DIR` if set and non-empty
/// 2. `$CARGO_MANIFEST_DIR/../../../fixtures/replay-corpus` (engine/fixtures/...)
/// 3. Walk ancestors of the compile-time manifest dir looking for
///    `fixtures/replay-corpus` or `engine/fixtures/replay-corpus`
/// 4. Relative `engine/fixtures/replay-corpus` from current dir
/// 5. Relative `fixtures/replay-corpus`
pub fn corpus_dir() -> PathBuf {
    #[cfg(any(test, feature = "agent_providers-test-mode"))]
    {
        if let Ok(dir) = std::env::var(CORPUS_ENV_DIR_OVERRIDE) {
            let t = dir.trim();
            if !t.is_empty() {
                return PathBuf::from(t);
            }
        }
    }
    // Compile-time manifest dir for the providers crate: engine/crates/providers
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let candidates = [
        manifest.join("../../../fixtures/replay-corpus"),
        manifest.join("../../fixtures/replay-corpus"),
        manifest.join("fixtures/replay-corpus"),
        PathBuf::from("engine/fixtures/replay-corpus"),
        PathBuf::from("fixtures/replay-corpus"),
        PathBuf::from("../fixtures/replay-corpus"),
        PathBuf::from("../../fixtures/replay-corpus"),
    ];
    for c in &candidates {
        if c.is_dir() {
            return c.clone();
        }
    }
    // Fallback: the canonical location relative to manifest, even if it does
    // not yet exist (caller will create or report missing).
    manifest.join("../../../fixtures/replay-corpus")
}

pub fn corpus_path(scenario: &str) -> PathBuf {
    corpus_dir().join(format!("{scenario}.jsonl"))
}

pub fn current_timestamp_iso() -> String {
    epoch_to_iso(now_epoch_secs())
}

// ── Redaction ─────────────────────────────────────────────────────────────────

fn redact_content_str(s: &str) -> String {
    // Replace obvious secret patterns; for generic JSON string values we
    // delegate to redact_json_value at the object level, this is the line-level
    // helper for free-form text deltas.
    let mut out = s.to_string();
    // Bearer token redaction (case-insensitive prefix)
    let lower = out.to_lowercase();
    if lower.contains("bearer ") {
        // Replace Bearer <token> with Bearer [REDACTED]
        let mut redacted = String::new();
        let mut idx = 0usize;
        let lower_bytes = lower.as_bytes();
        let orig_bytes = out.as_bytes();
        while idx < out.len() {
            if lower[idx..].starts_with("bearer ") {
                redacted.push_str(&out[idx..idx + 7]);
                redacted.push_str(REDACTED);
                idx += 7;
                // skip token chars until whitespace or end
                while idx < out.len() && !orig_bytes[idx].is_ascii_whitespace() {
                    idx += 1;
                }
                // also skip the lower mirror
                let _ = lower_bytes;
            } else {
                let ch_len = utf8_char_len(orig_bytes[idx]);
                redacted.push_str(&out[idx..idx + ch_len]);
                idx += ch_len;
            }
        }
        out = redacted;
    }
    // sk- style API keys
    if out.contains("sk-") {
        // naive: replace sk- followed by alphanum
        let mut redacted = String::new();
        let bytes = out.as_bytes();
        let mut i = 0usize;
        while i < out.len() {
            if out[i..].starts_with("sk-") {
                redacted.push_str(REDACTED);
                i += 3;
                while i < out.len() && bytes[i].is_ascii_alphanumeric() {
                    i += 1;
                }
                // swallow trailing alphanum/_/-
                while i < out.len()
                    && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_' || bytes[i] == b'-')
                {
                    i += 1;
                }
            } else {
                let ch_len = utf8_char_len(bytes[i]);
                redacted.push_str(&out[i..i + ch_len]);
                i += ch_len;
            }
        }
        out = redacted;
    }
    out
}

pub fn redact_delta(delta: &mut CompletionDelta) {
    if let Some(c) = delta.content.as_mut() {
        *c = redact_content_str(c);
    }
    if let Some(r) = delta.reasoning_content.as_mut() {
        *r = redact_content_str(r);
    }
    if let Some(a) = delta.tool_call_arguments_fragment.as_mut() {
        // Arguments may contain paths with secrets; redact JSON values with
        // secret-y keys if the fragment looks like JSON.
        if a.trim_start().starts_with('{') {
            if let Ok(mut v) = serde_json::from_str::<serde_json::Value>(a) {
                if redact_json_value(&mut v) {
                    *a = serde_json::to_string(&v).unwrap_or_else(|_| a.clone());
                } else {
                    // Still scan raw string for bearer/sk patterns
                    *a = redact_content_str(a);
                }
            } else {
                *a = redact_content_str(a);
            }
        } else {
            *a = redact_content_str(a);
        }
    }
}

pub fn redact_json_value(v: &mut serde_json::Value) -> bool {
    let mut changed = false;
    match v {
        serde_json::Value::Object(map) => {
            for (k, val) in map.iter_mut() {
                let lk = k.to_ascii_lowercase();
                if lk.contains("api_key")
                    || lk.contains("apikey")
                    || lk.contains("authorization")
                    || lk.contains("bearer")
                    || lk.contains("token")
                    || lk.contains("secret")
                    || lk.contains("password")
                    || lk.contains("credential")
                {
                    if !val.is_string() || val.as_str() != Some(REDACTED) {
                        *val = serde_json::Value::String(REDACTED.to_string());
                        changed = true;
                    }
                } else if redact_json_value(val) {
                    changed = true;
                }
            }
        }
        serde_json::Value::Array(arr) => {
            for item in arr.iter_mut() {
                if redact_json_value(item) {
                    changed = true;
                }
            }
        }
        serde_json::Value::String(s) => {
            let r = redact_content_str(s);
            if r != *s {
                *s = r;
                changed = true;
            }
        }
        _ => {}
    }
    changed
}

fn utf8_char_len(b: u8) -> usize {
    if b < 0x80 {
        1
    } else if b >> 5 == 0b110 {
        2
    } else if b >> 4 == 0b1110 {
        3
    } else {
        4
    }
}

// ── Header & freshness validation ────────────────────────────────────────────

fn parse_header_line(line: &str, path: &str, scenario: &str) -> Result<CorpusHeader, CorpusError> {
    let h = serde_json::from_str::<CorpusHeader>(line).map_err(|e| CorpusError::Json {
        path: path.to_string(),
        source: e,
    })?;
    if h.scenario != scenario {
        // Allow but warn — the filename is the canonical scenario.
        eprintln!(
            "WARN: corpus header scenario '{}' != filename scenario '{}' at {}",
            h.scenario, scenario, path
        );
    }
    Ok(h)
}

fn validate_header(header: &CorpusHeader, path: &str, scenario: &str) -> Result<(), CorpusError> {
    if header.version != CORPUS_VERSION {
        return Err(CorpusError::VersionMismatch {
            scenario: scenario.to_string(),
            expected: CORPUS_VERSION,
            got: header.version,
            path: path.to_string(),
        });
    }
    if !header.redacted {
        return Err(CorpusError::NotRedacted {
            scenario: scenario.to_string(),
            path: path.to_string(),
        });
    }
    Ok(())
}

pub fn check_freshness(header: &CorpusHeader, path: &str) -> Result<(), CorpusError> {
    if let Some(epoch) = iso_to_epoch(&header.recorded_at) {
        let now = now_epoch_secs();
        // Allow for modest clock skew (5 min); recorded_at in the future by <5m is not stale.
        let age = now.saturating_sub(epoch);
        if age > CORPUS_MAX_AGE_SECS {
            return Err(CorpusError::Stale {
                scenario: header.scenario.clone(),
                recorded_at: header.recorded_at.clone(),
                age_secs: age,
                max_age_secs: CORPUS_MAX_AGE_SECS,
                path: path.to_string(),
            });
        }
        Ok(())
    } else {
        // Fallback: file mtime freshness. If that also fails, treat timestamp as unparseable.
        let p = Path::new(path);
        if let Ok(meta) = std::fs::metadata(p) {
            if let Ok(mtime) = meta.modified() {
                if let Ok(age) = SystemTime::now().duration_since(mtime) {
                    if age.as_secs() > CORPUS_MAX_AGE_SECS {
                        return Err(CorpusError::Stale {
                            scenario: header.scenario.clone(),
                            recorded_at: header.recorded_at.clone(),
                            age_secs: age.as_secs(),
                            max_age_secs: CORPUS_MAX_AGE_SECS,
                            path: path.to_string(),
                        });
                    }
                    return Ok(());
                }
            }
        }
        Err(CorpusError::UnparseableTimestamp {
            scenario: header.scenario.clone(),
            recorded_at: header.recorded_at.clone(),
            path: path.to_string(),
        })
    }
}

pub fn freshness_warning(header: &CorpusHeader, path: &str) -> Option<String> {
    match check_freshness(header, path) {
        Ok(_) => None,
        Err(e) => Some(format!(
            "WARN: replay corpus freshness check failed for '{}': {e}",
            header.scenario
        )),
    }
}

pub fn warn_on_schema_mismatch(
    scenario: &str,
    path: &str,
    expected_version: u32,
    got_version: u32,
) {
    if expected_version != got_version {
        eprintln!(
            "WARN: replay corpus schema mismatch for '{scenario}' at {path}: expected version {expected_version}, got {got_version} — fixture vs live wire shape diverged; refresh with {CORPUS_ENV_RECORD}=1"
        );
    }
}

pub fn check_live_compat(scenario: &str) -> Option<String> {
    match load_header(scenario) {
        Ok(h) => {
            if h.version != CORPUS_VERSION {
                let msg = format!(
                    "WARN: replay corpus schema mismatch for '{scenario}': expected version {CORPUS_VERSION}, got {} — refresh with {CORPUS_ENV_RECORD}=1",
                    h.version
                );
                eprintln!("{msg}");
                return Some(msg);
            }
            if let Some(w) = freshness_warning(&h, &corpus_path(scenario).display().to_string()) {
                eprintln!("{w}");
                return Some(w);
            }
            None
        }
        Err(e) => {
            let msg = format!("WARN: replay corpus missing/stale for '{scenario}': {e}");
            eprintln!("{msg}");
            Some(msg)
        }
    }
}

// ── Corpus I/O ────────────────────────────────────────────────────────────────

pub fn load_header(scenario: &str) -> Result<CorpusHeader, CorpusError> {
    let path = corpus_path(scenario);
    let ps = path.display().to_string();
    let content = std::fs::read_to_string(&path).map_err(|e| {
        if e.kind() == std::io::ErrorKind::NotFound {
            CorpusError::Missing {
                scenario: scenario.to_string(),
                path: ps.clone(),
            }
        } else {
            CorpusError::Io {
                path: ps.clone(),
                source: e,
            }
        }
    })?;
    let first = content.lines().next().unwrap_or("");
    if first.trim().is_empty() {
        return Err(CorpusError::Json {
            path: ps.clone(),
            source: serde_json::from_str::<CorpusHeader>("").unwrap_err(),
        });
    }
    let header = parse_header_line(first, &ps, scenario)?;
    validate_header(&header, &ps, scenario)?;
    // Freshness is validated eagerly — stale corpus is a hard error on load;
    // callers that want a soft WARN can use freshness_warning.
    check_freshness(&header, &ps)?;
    Ok(header)
}

#[allow(dead_code)]
fn read_lines_after_header(path: &Path, ps: &str) -> Result<Vec<String>, CorpusError> {
    let content = std::fs::read_to_string(path).map_err(|e| CorpusError::Io {
        path: ps.to_string(),
        source: e,
    })?;
    let mut lines = content.lines();
    let _ = lines.next(); // header
    Ok(lines
        .filter(|l| !l.trim().is_empty())
        .map(|s| s.to_string())
        .collect())
}

pub fn load_deltas(scenario: &str) -> Result<Vec<CompletionDelta>, CorpusError> {
    let path = corpus_path(scenario);
    let ps = path.display().to_string();
    // Validate header first (version/redacted/freshness)
    let raw = std::fs::read_to_string(&path).map_err(|e| {
        if e.kind() == std::io::ErrorKind::NotFound {
            CorpusError::Missing {
                scenario: scenario.to_string(),
                path: ps.clone(),
            }
        } else {
            CorpusError::Io {
                path: ps.clone(),
                source: e,
            }
        }
    })?;
    let mut lines = raw.lines();
    let header_line = lines.next().unwrap_or("");
    if header_line.trim().is_empty() {
        return Err(CorpusError::Json {
            path: ps.clone(),
            source: serde_json::from_str::<CorpusHeader>("").unwrap_err(),
        });
    }
    let header = parse_header_line(header_line, &ps, scenario)?;
    validate_header(&header, &ps, scenario)?;
    check_freshness(&header, &ps)?;
    let mut deltas = Vec::new();
    for (idx, line) in lines.enumerate() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }
        // Allow error corpora to be skipped when loading as deltas; they will
        // have an {"error":...} line that is not a delta. We skip it with a WARN.
        if trimmed.contains("\"error\"") {
            eprintln!(
                "WARN: skipping error line {} in delta corpus '{}' at {}:{}",
                idx + 2,
                scenario,
                ps,
                trimmed
            );
            continue;
        }
        let mut delta: CompletionDelta =
            serde_json::from_str(trimmed).map_err(|e| CorpusError::Json {
                path: format!("{ps}:{}", idx + 2),
                source: e,
            })?;
        // Verify round-trip compat: fixture vs live shape mismatch should WARN
        let round = serde_json::to_string(&delta).map_err(|e| CorpusError::Json {
            path: ps.clone(),
            source: e,
        })?;
        let reparsed: CompletionDelta =
            serde_json::from_str(&round).map_err(|e| CorpusError::Json {
                path: ps.clone(),
                source: e,
            })?;
        let _ = reparsed;
        // Live compat check: if the fixture delta fails to re-serialize with the
        // current struct (e.g. new required field), we will have already errored;
        // otherwise WARN if the fixture's JSON had unknown fields that were dropped.
        let original_value: serde_json::Value =
            serde_json::from_str(trimmed).unwrap_or(serde_json::Value::Null);
        let round_value: serde_json::Value =
            serde_json::from_str(&round).unwrap_or(serde_json::Value::Null);
        if original_value != round_value {
            // Unknown or renamed fields were dropped — signal staleness.
            eprintln!("WARN: replay corpus schema mismatch for '{scenario}' at {ps}:{} — fixture vs live wire shape diverged (original != round-tripped)", idx + 2);
        }
        redact_delta(&mut delta);
        deltas.push(delta);
    }
    Ok(deltas)
}

pub fn load_stored_errors(scenario: &str) -> Result<Vec<StoredError>, CorpusError> {
    let path = corpus_path(scenario);
    let ps = path.display().to_string();
    let raw = std::fs::read_to_string(&path).map_err(|e| {
        if e.kind() == std::io::ErrorKind::NotFound {
            CorpusError::Missing {
                scenario: scenario.to_string(),
                path: ps.clone(),
            }
        } else {
            CorpusError::Io {
                path: ps.clone(),
                source: e,
            }
        }
    })?;
    let mut lines = raw.lines();
    let header_line = lines.next().unwrap_or("");
    let header = parse_header_line(header_line, &ps, scenario)?;
    validate_header(&header, &ps, scenario)?;
    check_freshness(&header, &ps)?;
    let mut out = Vec::new();
    for (idx, line) in lines.enumerate() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }
        if let Ok(wrapped) = serde_json::from_str::<CorpusErrorLine>(trimmed) {
            out.push(wrapped.error);
        } else if let Ok(err) = serde_json::from_str::<StoredError>(trimmed) {
            out.push(err);
        } else {
            return Err(CorpusError::Json {
                path: format!("{ps}:{}", idx + 2),
                source: serde_json::from_str::<serde_json::Value>(trimmed).unwrap_err(),
            });
        }
    }
    Ok(out)
}

