    fn apply_to_reassembler(
        script: &DeltaScript,
        reassembler: &mut ToolCallChunkReassembler,
    ) -> Vec<ToolCall> {
        let mut triggered_tool_end = false;
        for delta in &script.deltas {
            if delta.tool_call_name.is_some()
                || delta.tool_call_arguments_fragment.is_some()
                || delta.id.is_some()
            {
                reassembler
                    .process_delta(
                        delta.index as u64,
                        delta.id.as_deref(),
                        delta.tool_call_name.as_deref(),
                        delta.tool_call_arguments_fragment.as_deref().unwrap_or(""),
                    )
                    .expect("scripted delta is well-formed");
            }
            if delta.finish_reason.as_deref() == Some("tool_calls") {
                triggered_tool_end = true;
            }
        }
        if triggered_tool_end {
            reassembler
                .drain_completed()
                .expect("scripted tool call is complete")
                .into_iter()
                .map(|call| ToolCall {
                    id: call.id,
                    name: call.name,
                    arguments_json: call.arguments,
                })
                .collect()
        } else {
            Vec::new()
        }
    }

