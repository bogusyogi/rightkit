/// Replay-of-record transcript consumer. Each call to `apply(delta)`
/// records the delta; `replay()` walks the recording and exposes it for
/// comparison or for replaying into a fresh client.
#[derive(Debug, Default)]
pub struct ReplayRecorder {
    pub script_name: String,
    pub recorded: Vec<CompletionDelta>,
    pub malformed_event_count: u32,
}

impl ReplayRecorder {
    pub fn new(script_name: impl Into<String>) -> Self {
        Self {
            script_name: script_name.into(),
            ..Default::default()
        }
    }

    /// Apply a delta; counts malformed frames in `content`. Deterministic —
    /// any `content` containing non-printable ASCII bytes counts as a
    /// malformed frame. The real transport's SSE parser would emit a
    /// [`ProviderError::Sse`] in the same situation; the fixture mirrors
    /// that signal without parsing bytes.
    pub fn apply(&mut self, delta: CompletionDelta) {
        let malformed = delta
            .content
            .as_deref()
            .map(|content| content.bytes().any(|b| b < 0x09 || (b > 0x0d && b < 0x20)))
            .unwrap_or(false);
        if malformed {
            self.malformed_event_count += 1;
        }
        self.recorded.push(delta);
    }

    pub fn replay_into(&self, sink: &mut ReplayRecorder) -> usize {
        let mut count = 0usize;
        for d in &self.recorded {
            sink.apply(d.clone());
            count += 1;
        }
        count
    }

    /// Return the recorded text fragments in order (skips null/empty),
    /// concatenated with no delimiter — the test asserts on equality.
    pub fn assembled_text(&self) -> String {
        self.recorded
            .iter()
            .filter_map(|d| d.content.clone())
            .collect()
    }
}

/// Producer side: crafts a [`CompletedTurn`] from a [`DeltaScript`].
///
/// `produce` is reference-only — the real provider does the actual
/// transport; this harness just materializes a stable replay value from
/// the script so tests can assert determinism.
#[derive(Debug, Default)]
pub struct ScriptedProducer {
    states: Mutex<HashMap<String, usize>>,
}

impl ScriptedProducer {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn produce(&self, script: &DeltaScript) -> CompletedTurn {
        let mut states = self.states.lock().unwrap();
        *states.entry(script.name.clone()).or_insert(0) += 1;
        CompletedTurn {
            text: script
                .deltas
                .iter()
                .filter_map(|d| d.content.clone())
                .collect(),
            ..Default::default()
        }
    }
}

/// Retry/failover fixture: a typed sequence of [`FailoverEvent`]s emitted
/// by the (removed) local failover middleware, as the corpus stores them; used
/// standalone to assert corpus determinism.
#[derive(Debug, Clone)]
pub struct FailoverScript {
    pub name: String,
    pub events: Vec<FailoverEvent>,
}

impl FailoverScript {
    fn load_or_fallback(name: &str, fallback: Vec<FailoverEvent>) -> Self {
        match load_failover_events(name) {
            Ok(events) => Self {
                name: name.to_string(),
                events,
            },
            Err(e) => {
                eprintln!("WARN: FailoverScript '{name}' corpus load failed ({e}) — using fallback fixture; refresh with {CORPUS_ENV_RECORD}=1");
                if is_record_mode() {
                    let _ = record_failover_events(name, &fallback, None, None);
                }
                Self {
                    name: name.to_string(),
                    events: fallback,
                }
            }
        }
    }

    /// Two attempts on the primary (both transient 503), then success on
    /// the secondary's first try.
    pub fn retry_then_succeed() -> Self {
        let fallback = vec![
            FailoverEvent {
                from: "primary".into(),
                to: Some("secondary".into()),
                reason: "transient 503".into(),
                breaker_skipped: false,
            },
            FailoverEvent {
                from: "secondary".into(),
                to: Some("primary".into()),
                reason: "upstream rejected".into(),
                breaker_skipped: false,
            },
        ];
        Self::load_or_fallback("retry_then_succeed", fallback)
    }

    /// Policy-exhausted: every route attempted, no success.
    pub fn policy_exhausted() -> Self {
        let fallback = vec![
            FailoverEvent {
                from: "primary".into(),
                to: Some("secondary".into()),
                reason: "503".into(),
                breaker_skipped: false,
            },
            FailoverEvent {
                from: "secondary".into(),
                to: Some("tertiary".into()),
                reason: "503".into(),
                breaker_skipped: true,
            },
        ];
        Self::load_or_fallback("policy_exhausted", fallback)
    }
}

/// Cancellation token the replay harness observes. Cancelling mid-run
/// aborts the next `apply` call.
#[derive(Debug, Default, Clone)]
pub struct CancelToken {
    inner: Arc<Mutex<bool>>,
}

impl CancelToken {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn cancel(&self) {
        *self.inner.lock().unwrap() = true;
    }

    pub fn is_cancelled(&self) -> bool {
        *self.inner.lock().unwrap()
    }

    pub fn gate(&self) -> Result<(), ProviderError> {
        if self.is_cancelled() {
            Err(ProviderError::Network("cancelled".into()))
        } else {
            Ok(())
        }
    }
}

/// End-of-stream usage accounting the replay harness collects.
#[derive(Debug, Default, Clone, PartialEq, Serialize, Deserialize)]
pub struct UsageRollup {
    pub prompt_tokens: u64,
    pub completion_tokens: u64,
    pub cache_read_tokens: u64,
    pub cache_creation_tokens: u64,
}

impl UsageRollup {
    pub fn from_rollups(samples: &[Self]) -> Self {
        let mut total = Self::default();
        for s in samples {
            total.prompt_tokens += s.prompt_tokens;
            total.completion_tokens += s.completion_tokens;
            total.cache_read_tokens += s.cache_read_tokens;
            total.cache_creation_tokens += s.cache_creation_tokens;
        }
        total
    }

    pub fn is_zero(&self) -> bool {
        self.prompt_tokens == 0
            && self.completion_tokens == 0
            && self.cache_read_tokens == 0
            && self.cache_creation_tokens == 0
    }
}

/// A pre-baked usage sequence the tests replay.
