#![allow(clippy::result_large_err)]

//! Provider record/replay corpus — recorded, redacted, versioned.
//!
//! This module replaces the prior hand-authored fixture-only approach with a
//! recorded corpus loaded from `engine/fixtures/replay-corpus/*.jsonl`.
//!
//! Design (FM-187):
//! - **Recorded**: fixtures are captured from live provider traffic when
//!   `RIGHTKIT_RECORD_REPLAY=1` is set. `OpenAiCompatClient` calls
//!   [`maybe_record_deltas`] / [`maybe_record_turn`] after each successful
//!   turn; the corpus is written as JSONL with a versioned, redacted header.
//! - **Redacted**: every write passes through `redact_value` /
//!   [`redact_json_value`] and [`redact_delta`]; API keys, bearer tokens, and
//!   secret-carrying JSON keys are replaced with `[REDACTED]` before touching
//!   disk. Headers set `redacted: true`; loaders reject `redacted: false`.
//! - **Versioned**: [`CORPUS_VERSION`] is the on-disk schema version. Headers
//!   carry `version`; loaders error on `version != CORPUS_VERSION` and emit a
//!   visible `WARN:` so a stale corpus never silently passes. See
//!   [`warn_on_schema_mismatch`].
//! - **Freshness**: every header carries `recorded_at` (RFC3339, generated by
//!   [`current_timestamp_iso`]). On load [`check_freshness`] parses that
//!   timestamp (or falls back to file mtime) and rejects entries older than
//!   [`CORPUS_MAX_AGE_DAYS`] (90 days). Callers can also call
//!   [`freshness_warning`] for a non-fatal WARN path.
//! - **Scenarios**: the corpus ships named scenarios covering normal streaming,
//!   tool calls, malformed chunks, cancellation, plus the three required named
//!   error cases `auth_failure`, `rate_limit`, `context_overflow`, and the
//!   failover / usage companion corpora. Missing scenario files are hard
//!   errors; see [`ensure_required_scenarios`].
//! - **Mismatch warn**: [`warn_on_schema_mismatch`] / [`check_live_compat`]
//!   detect a live wire shape that the fixture cannot round-trip and emit a
//!   `WARN: replay corpus schema mismatch` instead of silently succeeding.
//!
//! File layout (one JSONL per scenario, e.g. `short_text_reply.jsonl`):
//! ```text
//! {"version":1,"scenario":"short_text_reply","recorded_at":"2026-08-10T00:00:00Z","redacted":true,"provider":"openrouter","model":"test-model"}
//! {"index":0,"id":"chatcmpl-1","role":"assistant","content":"Don", ...}
//! {"index":0,"id":null,"role":null,"content":"e.", ...}
//! ```
//! Error corpora (`auth_failure`, `rate_limit`, `context_overflow`) store a
//! second line `{ "error": { "kind": "...", ... } }`. Failover corpora store
//! `FailoverEvent` JSON per line after the header. Usage corpora store
//! `UsageRollup` JSON per line.
//!
//! Recording stays local: `rightkit_llm` raw capture covers only non-streaming
//! `complete()` responses and keeps raw bytes, so it does not produce the streaming
//! `CompletionDelta` corpus. Secrets are removed by `redact_delta` / `redact_json_value`
//! before any write, and `is_record_mode` is true only in test and `replay-record` builds.

/// One route-failover event. The route failover that produces these events is
/// `crate::failover`; the failover corpus stores each event as one JSON
/// line (`to` is stored as an empty string when no further route was tried).
