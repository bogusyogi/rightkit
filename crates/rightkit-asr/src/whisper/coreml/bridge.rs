//! Minimal CoreML.framework bridge (pure Rust on `objc2-core-ml`): load a
//! precompiled `.mlmodelc`, build `MLMultiArray` inputs, run predictions, and
//! read outputs honouring real element strides.
//!
//! Donor: HeardRight `heardright-inference/src/coreml/{stage,multiarray}.rs`.
//! Load-bearing subtlety kept from the donor: CoreML outputs are NOT guaranteed
//! C-contiguous, so reads gather through `MLMultiArray.strides()`.
//! Objective-C exceptions are caught with `objc2::exception::catch` so they can
//! never unwind into Rust (release profiles may use `panic = "abort"`).
#![allow(deprecated)]

use half::f16;
use objc2::rc::{autoreleasepool, Retained};
use objc2::runtime::{AnyObject, ProtocolObject};
use objc2::AnyThread;
use objc2_core_ml::{
    MLComputeUnits, MLDictionaryFeatureProvider, MLFeatureProvider, MLFeatureValue, MLModel,
    MLModelConfiguration, MLMultiArray, MLMultiArrayDataType,
};
use objc2_foundation::{NSArray, NSDictionary, NSError, NSNumber, NSString, NSURL};
use std::panic::AssertUnwindSafe;
use std::path::{Path, PathBuf};

fn nserr(e: &NSError) -> String {
    e.localizedDescription().to_string()
}

/// Which silicon CoreML may use.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum ComputeUnits {
    /// CPU + Neural Engine (GPU on Intel). The shipping default.
    #[default]
    Automatic,
    CpuOnly,
    CpuAndGpu,
    All,
}

/// One loaded CoreML model.
pub struct Stage {
    model: Retained<MLModel>,
}

// SAFETY: Apple documents MLModel as thread-safe; objc2 just does not encode
// it. Stage exposes only `&self` prediction.
unsafe impl Send for Stage {}

impl Stage {
    pub fn load(path: &Path, units: ComputeUnits) -> Result<Self, String> {
        if path.extension().and_then(|e| e.to_str()) != Some("mlmodelc") {
            return Err(format!(
                "{} is not a compiled .mlmodelc bundle",
                path.display()
            ));
        }
        if !path.is_dir() {
            return Err(format!("CoreML model not found: {}", path.display()));
        }
        autoreleasepool(|_| unsafe {
            let config = MLModelConfiguration::new();
            #[cfg(not(target_arch = "x86_64"))]
            let automatic = MLComputeUnits::CPUAndNeuralEngine;
            #[cfg(target_arch = "x86_64")]
            let automatic = MLComputeUnits::CPUAndGPU;
            config.setComputeUnits(match units {
                ComputeUnits::Automatic => automatic,
                ComputeUnits::CpuOnly => MLComputeUnits::CPUOnly,
                ComputeUnits::CpuAndGpu => MLComputeUnits::CPUAndGPU,
                ComputeUnits::All => MLComputeUnits::All,
            });
            let url = NSURL::fileURLWithPath(&NSString::from_str(&path.to_string_lossy()));
            let loaded = objc2::exception::catch(AssertUnwindSafe(|| {
                MLModel::modelWithContentsOfURL_configuration_error(&url, &config)
            }))
            .map_err(|_| format!("CoreML raised an exception loading {}", path.display()))?;
            let model = loaded.map_err(|e| format!("load {}: {}", path.display(), nserr(&e)))?;
            Ok(Self { model })
        })
    }

    /// Load a `.mlmodelc` directly, or compile a `.mlpackage` / `.mlmodel` once
    /// into `cache_dir` (keyed by source path) and load the cached
    /// `.mlmodelc`. Packaged apps run from read-only locations, so the caller
    /// supplies a writable `cache_dir`; `None` compiles beside the source.
    pub fn load_any(path: &Path, units: ComputeUnits, cache_dir: Option<&Path>) -> Result<Self, String> {
        if path.extension().and_then(|e| e.to_str()) == Some("mlmodelc") {
            return Self::load(path, units);
        }
        if !path.exists() {
            return Err(format!("CoreML model not found: {}", path.display()));
        }
        Self::load(&compiled_cache(path, cache_dir)?, units)
    }

    /// Output feature names, in dictionary order.
    pub fn output_names(&self) -> Vec<String> {
        unsafe {
            let desc = self.model.modelDescription();
            desc.outputDescriptionsByName().allKeys().iter().map(|k| k.to_string()).collect()
        }
    }

    /// Input feature names, in dictionary order.
    #[allow(dead_code)]
    pub fn input_names(&self) -> Vec<String> {
        unsafe {
            let desc = self.model.modelDescription();
            desc.inputDescriptionsByName().allKeys().iter().map(|k| k.to_string()).collect()
        }
    }

    /// All outputs whose multiarray shape equals `want`, sorted by name
    /// (autogenerated `var_NN` names sort into declaration order).
    pub fn outputs_by_shape(&self, want: &[usize]) -> Vec<String> {
        unsafe {
            let desc = self.model.modelDescription();
            let by_name = desc.outputDescriptionsByName();
            let mut hits = Vec::new();
            for key in by_name.allKeys().iter() {
                if let Some(fd) = by_name.objectForKey(&key) {
                    if let Some(c) = fd.multiArrayConstraint() {
                        let shape: Vec<usize> =
                            c.shape().iter().map(|n| n.integerValue() as usize).collect();
                        if shape == want {
                            hits.push(key.to_string());
                        }
                    }
                }
            }
            hits.sort();
            hits
        }
    }

    pub fn output_by_shape(&self, want: &[usize]) -> Result<String, String> {
        self.outputs_by_shape(want)
            .into_iter()
            .next()
            .ok_or_else(|| format!("no output with shape {want:?}"))
    }

    /// Run a prediction, return one named output.
    pub fn predict(
        &self,
        inputs: &[(&str, &Retained<MLMultiArray>)],
        out_name: &str,
    ) -> Result<Retained<MLMultiArray>, String> {
        Ok(self.predict_multi(inputs, &[out_name])?.remove(0))
    }

    /// Run a prediction and return the named outputs in `out_names` order.
    pub fn predict_multi(
        &self,
        inputs: &[(&str, &Retained<MLMultiArray>)],
        out_names: &[&str],
    ) -> Result<Vec<Retained<MLMultiArray>>, String> {
        autoreleasepool(|_| unsafe {
            let keys: Vec<Retained<NSString>> =
                inputs.iter().map(|(k, _)| NSString::from_str(k)).collect();
            let vals: Vec<Retained<MLFeatureValue>> = inputs
                .iter()
                .map(|(_, v)| MLFeatureValue::featureValueWithMultiArray(v))
                .collect();
            let key_refs: Vec<&NSString> = keys.iter().map(|k| k.as_ref()).collect();
            let val_refs: Vec<&MLFeatureValue> = vals.iter().map(|v| v.as_ref()).collect();
            let dict: Retained<NSDictionary<NSString, MLFeatureValue>> =
                NSDictionary::from_slices(&key_refs, &val_refs);
            let provider = MLDictionaryFeatureProvider::initWithDictionary_error(
                MLDictionaryFeatureProvider::alloc(),
                // SAFETY: NSDictionary<NSString, MLFeatureValue> is layout-identical to
                // NSDictionary<NSString, AnyObject> (MLFeatureValue: NSObject).
                std::mem::transmute::<
                    &NSDictionary<NSString, MLFeatureValue>,
                    &NSDictionary<NSString, AnyObject>,
                >(&dict),
            )
            .map_err(|e| format!("feature provider: {}", nserr(&e)))?;
            let provider_obj: &ProtocolObject<dyn MLFeatureProvider> =
                ProtocolObject::from_ref(&*provider);
            let result = objc2::exception::catch(AssertUnwindSafe(|| {
                self.model.predictionFromFeatures_error(provider_obj)
            }))
            .map_err(|_| "CoreML raised an exception during prediction".to_string())?
            .map_err(|e| format!("predict: {}", nserr(&e)))?;
            let mut outs = Vec::with_capacity(out_names.len());
            for name in out_names {
                let fv = result
                    .featureValueForName(&NSString::from_str(name))
                    .ok_or_else(|| format!("output `{name}` missing"))?;
                outs.push(
                    fv.multiArrayValue()
                        .ok_or_else(|| format!("output `{name}` is not a multiarray"))?,
                );
            }
            Ok(outs)
        })
    }
}

fn compiled_cache(path: &Path, cache_dir: Option<&Path>) -> Result<PathBuf, String> {
    use std::hash::{Hash, Hasher};
    let dest = match cache_dir {
        Some(dir) => {
            let mut h = std::collections::hash_map::DefaultHasher::new();
            path.to_string_lossy().hash(&mut h);
            let stem: String = path
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("model")
                .chars()
                .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '-' })
                .collect();
            dir.join(format!("{stem}-{:016x}.mlmodelc", h.finish()))
        }
        None => path.with_extension("mlmodelc"),
    };
    if dest.join("coremldata.bin").exists() || dest.join("model.mil").exists() {
        return Ok(dest);
    }
    let compiled = autoreleasepool(|_| unsafe {
        let url = NSURL::fileURLWithPath(&NSString::from_str(&path.to_string_lossy()));
        MLModel::compileModelAtURL_error(&url)
            .map_err(|e| format!("compile {}: {}", path.display(), nserr(&e)))
            .and_then(|u| {
                u.path()
                    .map(|p| PathBuf::from(p.to_string()))
                    .ok_or_else(|| format!("compiled URL has no path for {}", path.display()))
            })
    })?;
    let tmp = dest.with_extension("mlmodelc.tmp");
    let _ = std::fs::remove_dir_all(&tmp);
    copy_dir(&compiled, &tmp)?;
    let _ = std::fs::remove_dir_all(&dest);
    std::fs::rename(&tmp, &dest).map_err(|e| format!("install {}: {e}", dest.display()))?;
    Ok(dest)
}

fn copy_dir(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::create_dir_all(to).map_err(|e| format!("create {}: {e}", to.display()))?;
    for entry in std::fs::read_dir(from).map_err(|e| format!("read {}: {e}", from.display()))? {
        let entry = entry.map_err(|e| e.to_string())?;
        let (src, dst) = (entry.path(), to.join(entry.file_name()));
        let ty = entry.file_type().map_err(|e| e.to_string())?;
        if ty.is_dir() {
            copy_dir(&src, &dst)?;
        } else if ty.is_file() {
            std::fs::copy(&src, &dst).map_err(|e| format!("copy {}: {e}", src.display()))?;
        }
    }
    Ok(())
}

unsafe fn new_marray(
    dims: &[usize],
    dt: MLMultiArrayDataType,
) -> Result<Retained<MLMultiArray>, String> {
    let nums: Vec<Retained<NSNumber>> = dims
        .iter()
        .map(|&d| NSNumber::new_isize(d as isize))
        .collect();
    let refs: Vec<&NSNumber> = nums.iter().map(|n| n.as_ref()).collect();
    let shape = NSArray::from_slice(&refs);
    MLMultiArray::initWithShape_dataType_error(MLMultiArray::alloc(), &shape, dt)
        .map_err(|e| format!("MLMultiArray alloc: {}", nserr(&e)))
}

fn check_len(dims: &[usize], len: usize) -> Result<(), String> {
    let want: usize = dims.iter().product();
    if want == len {
        Ok(())
    } else {
        Err(format!("shape {dims:?} needs {want} elements, got {len}"))
    }
}

pub fn ml_i32(dims: &[usize], data: &[i32]) -> Result<Retained<MLMultiArray>, String> {
    check_len(dims, data.len())?;
    unsafe {
        let arr = new_marray(dims, MLMultiArrayDataType::Int32)?;
        let ptr = arr.dataPointer().as_ptr() as *mut i32;
        std::ptr::copy_nonoverlapping(data.as_ptr(), ptr, data.len());
        Ok(arr)
    }
}

pub fn ml_f16(dims: &[usize], data: &[f32]) -> Result<Retained<MLMultiArray>, String> {
    check_len(dims, data.len())?;
    unsafe {
        let arr = new_marray(dims, MLMultiArrayDataType::Float16)?;
        let ptr = arr.dataPointer().as_ptr() as *mut f16;
        for (i, &x) in data.iter().enumerate() {
            *ptr.add(i) = f16::from_f32(x);
        }
        Ok(arr)
    }
}

/// Write one f16 element by linear C-contiguous index (in-place KV cache updates).
pub fn f16_set(arr: &MLMultiArray, idx: usize, val: f32) {
    unsafe { *(arr.dataPointer().as_ptr() as *mut f16).add(idx) = f16::from_f32(val) }
}

pub fn i32_set(arr: &MLMultiArray, idx: usize, val: i32) {
    unsafe { *(arr.dataPointer().as_ptr() as *mut i32).add(idx) = val }
}

/// Row-padded fast path: when the innermost stride is 1 and the outer dims
/// stack cleanly on the row pitch, copy rows wholesale. CoreML encoders emit
/// padded rows (e.g. `1x1024x188` with strides `196608x192x1`); the element-wise
/// gather costs more than the prediction itself there. Donor: HeardRight
/// `coreml/multiarray.rs::row_layout`.
fn row_layout(shape: &[usize], strides: &[isize]) -> Option<(usize, usize, usize)> {
    if shape.len() < 2 || *strides.last()? != 1 {
        return None;
    }
    let row_len = *shape.last()?;
    let row_pitch = usize::try_from(strides[shape.len() - 2]).ok()?;
    if row_pitch < row_len {
        return None;
    }
    let mut expected = row_pitch;
    for dim in (1..shape.len() - 1).rev() {
        expected = expected.checked_mul(shape[dim])?;
        if usize::try_from(strides[dim - 1]).ok()? != expected {
            return None;
        }
    }
    let total = shape.iter().try_fold(1usize, |p, d| p.checked_mul(*d))?;
    Some((row_len, row_pitch, total / row_len.max(1)))
}

unsafe fn gather<T: Copy, O>(arr: &MLMultiArray, conv: impl Fn(T) -> O) -> Vec<O> {
    let shape: Vec<usize> = arr.shape().iter().map(|n| n.integerValue() as usize).collect();
    let strides: Vec<isize> = arr.strides().iter().map(|n| n.integerValue()).collect();
    let ptr = arr.dataPointer().as_ptr() as *const T;
    let total: usize = shape.iter().product();
    let ndim = shape.len();
    let mut out = Vec::with_capacity(total);
    if let Some((row_len, row_pitch, rows)) = row_layout(&shape, &strides) {
        for row in 0..rows {
            let src = ptr.add(row * row_pitch);
            for i in 0..row_len {
                out.push(conv(*src.add(i)));
            }
        }
        return out;
    }
    let mut idx = vec![0usize; ndim];
    for _ in 0..total {
        let off: isize = (0..ndim).map(|k| idx[k] as isize * strides[k]).sum();
        out.push(conv(*ptr.offset(off)));
        for k in (0..ndim).rev() {
            idx[k] += 1;
            if idx[k] < shape[k] {
                break;
            }
            idx[k] = 0;
        }
    }
    out
}

/// Read an f16 MLMultiArray as f32 in C-contiguous order, honouring strides.
pub fn read_f16(arr: &MLMultiArray) -> Vec<f32> {
    unsafe { gather::<f16, f32>(arr, |x| x.to_f32()) }
}

/// Read an f32 MLMultiArray in C-contiguous order, honouring strides.
#[allow(dead_code)]
pub fn read_f32(arr: &MLMultiArray) -> Vec<f32> {
    unsafe { gather::<f32, f32>(arr, |x| x) }
}
