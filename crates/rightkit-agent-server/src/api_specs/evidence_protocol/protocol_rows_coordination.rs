fn protocol_provenance_coordination_evidence_row(
    session: &crate::api::LiveSession,
    event: ProtocolEvent,
) -> Option<ProtocolProvenanceEvidence> {
    match event {
        ProtocolEvent::AgentQueryIssued {
            seq,
            created_at,
            query_id,
            from_role,
            to_role,
            query_type,
            expected_format,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("agent_query:{query_id}/issued"),
            kind: "agent_query_issued".to_string(),
            producer: "agent_coordination".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: format!("{from_role} asked {to_role} for {query_type}"),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "queryId": query_id,
                "fromRole": from_role,
                "toRole": to_role,
                "queryType": query_type,
                "expectedFormat": expected_format,
            }),
        }),
        ProtocolEvent::AgentQueryResponded {
            seq,
            created_at,
            query_id,
            from_role,
            to_role,
            confidence,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("agent_query:{query_id}/responded"),
            kind: "agent_query_responded".to_string(),
            producer: "agent_coordination".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: format!(
                "{from_role} responded to {to_role} with confidence {:.2}",
                confidence
            ),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "queryId": query_id,
                "fromRole": from_role,
                "toRole": to_role,
                "confidence": confidence,
            }),
        }),
        ProtocolEvent::HumanSteeringInjected {
            seq,
            created_at,
            injected_by,
            content_preview,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("human_steering:{seq}"),
            kind: "human_steering_injected".to_string(),
            producer: "operator_steering".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: format!("Human steering injected by {injected_by}"),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "injectedBy": injected_by,
                "contentPreview": content_preview,
            }),
        }),
        ProtocolEvent::SubAgentSpawned {
            seq,
            created_at,
            sub_session_id,
            role,
            task_title,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("subagent:{sub_session_id}/spawned"),
            kind: "subagent_spawned".to_string(),
            producer: "subagent_orchestrator".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: format!("Spawned {role} subagent for {task_title}"),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "subSessionId": sub_session_id,
                "role": role,
                "taskTitle": task_title,
            }),
        }),
        ProtocolEvent::SubAgentCompleted {
            seq,
            created_at,
            sub_session_id,
            role,
            success,
            summary,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("subagent:{sub_session_id}/completed"),
            kind: "subagent_completed".to_string(),
            producer: "subagent_orchestrator".to_string(),
            shippable: success,
            verdict_passed: Some(success),
            verdict_summary: format!("{role} subagent completed: {summary}"),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "subSessionId": sub_session_id,
                "role": role,
                "success": success,
                "summary": summary,
            }),
        }),
        ProtocolEvent::SubAgentCancelled {
            seq,
            created_at,
            sub_session_id,
            role,
            cancelled_by,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("subagent:{sub_session_id}/cancelled"),
            kind: "subagent_cancelled".to_string(),
            producer: "subagent_orchestrator".to_string(),
            shippable: false,
            verdict_passed: Some(false),
            verdict_summary: format!("{role} subagent cancelled by {cancelled_by}"),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "subSessionId": sub_session_id,
                "role": role,
                "cancelledBy": cancelled_by,
            }),
        }),
        ProtocolEvent::UserQuestionAsked {
            seq,
            created_at,
            question_id,
            questions,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("user_question:{question_id}/asked"),
            kind: "user_question_asked".to_string(),
            producer: "operator_interaction".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: format!("Asked {} operator question(s)", questions.len()),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "questionId": question_id,
                "questions": questions,
            }),
        }),
        ProtocolEvent::UserQuestionAnswered {
            seq,
            created_at,
            question_id,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("user_question:{question_id}/answered"),
            kind: "user_question_answered".to_string(),
            producer: "operator_interaction".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: "Operator question answered".to_string(),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "questionId": question_id,
            }),
        }),
        ProtocolEvent::PlanPresented {
            seq,
            created_at,
            plan_id,
            plan,
            ..
        } => Some(ProtocolProvenanceEvidence {
            seq,
            created_at,
            path: format!("plan:{plan_id}/presented"),
            kind: "plan_presented".to_string(),
            producer: "plan_mode".to_string(),
            shippable: false,
            verdict_passed: None,
            verdict_summary: "Plan presented for operator review".to_string(),
            payload: serde_json::json!({
                "sessionId": session.id,
                "seq": seq,
                "planId": plan_id,
                "plan": plan,
            }),
        }),
        _ => None,
    }
}
