//! Resolved theme tokens for UIs that are not web views (overlay-win, Ember, SwiftRight hosts).
//!
//! `@rightkit/theme` resolves a `brand.json` into CSS custom properties, but its resolver (the derived
//! dark accent and the WCAG contrast repair) exists only in TypeScript, so native UIs hand-coded their
//! colours. This crate is the same resolver in Rust: [`resolve_brand`] gives the per-mode palette and
//! [`design_tokens`] / [`design_tokens_json`] emit it as W3C design-token (DTCG) JSON, one group per mode.
//!
//! The brand file is the single source; `@rightkit/theme` stays the web owner and both read the same
//! `brand.json`. Colour maths and the resolution rules are ported line for line from
//! `packages/theme/src/color.ts` and `brand.ts`.

pub mod brand;
pub mod color;

use std::collections::BTreeMap;

use serde_json::{json, Map, Value};

pub use brand::{
    parse_brand, resolve_brand, suite_defaults, BrandFile, Mode, ResolvedBrand, ThemeError,
    OVERRIDABLE_TOKENS,
};

/// Token names for one mode, without the `--rk-` CSS prefix, in a flat map (sorted by name):
///
/// - every suite colour (`chrome`, `plane`, `elevated`, `panel`, `sunk`, `ink`, `ink-2`, `ink-3`, `ok`,
///   `warn`, `bad`, `stage`, `success*`, `warning*`, `star`, `accent-ink`, and any brand override), and
/// - the brand palette: `brand-mark` (the logo colour), `brand-action`, `brand-ink`, the rest of the
///   `brand-*` keys, and `accent`, an alias of `brand-action`.
///
/// Values are `#RRGGBB` or the `rgba(...)` text the suite defaults use for translucent fills.
pub fn mode_tokens(resolved: &ResolvedBrand, mode: Mode) -> BTreeMap<String, String> {
    let mut out: BTreeMap<String, String> = resolved.effective[&mode].clone();
    let palette = &resolved.palette[&mode];
    for (key, value) in palette {
        match key.as_str() {
            "brand" => {
                out.insert("brand-mark".into(), value.clone());
            }
            _ => {
                out.insert(key.clone(), value.clone());
            }
        }
    }
    if let Some(action) = palette.get("brand-action") {
        out.insert("accent".into(), action.clone());
    }
    out
}

fn color_token(value: &str) -> Value {
    json!({ "$type": "color", "$value": value })
}

/// The suite motion scale as DTCG tokens (`SUITE_MOTION`: not per mode).
fn motion_tokens() -> Value {
    json!({
        "$type": "duration",
        "dur-1": { "$value": "120ms" },
        "ease-out": { "$type": "cubicBezier", "$value": [0.16, 1, 0.3, 1] },
        "ease-spring": { "$type": "cubicBezier", "$value": [0.34, 1.56, 0.64, 1] },
    })
}

/// W3C design-token document: `{ "name", "light": { <token>: { "$type": "color", "$value": "#..." } },
/// "dark": { ... }, "motion": { ... } }`. Deterministic: the same brand gives the same bytes.
pub fn design_tokens(brand: &BrandFile) -> Result<Value, ThemeError> {
    let resolved = resolve_brand(brand)?;
    let mut doc = Map::new();
    doc.insert(
        "$description".into(),
        Value::String(format!(
            "Resolved theme tokens for {} (generated by rightkit-theme; edit the brand file)",
            brand.name
        )),
    );
    for mode in Mode::ALL {
        let group: Map<String, Value> = mode_tokens(&resolved, mode)
            .into_iter()
            .map(|(name, value)| (name, color_token(&value)))
            .collect();
        doc.insert(mode.as_str().into(), Value::Object(group));
    }
    doc.insert("motion".into(), motion_tokens());
    if let Some(font) = &brand.wordmark_font {
        doc.insert(
            "wordmarkFont".into(),
            json!({ "$type": "fontFamily", "$value": font }),
        );
    }
    Ok(Value::Object(doc))
}

/// [`design_tokens`] as pretty-printed JSON text ending in a newline.
pub fn design_tokens_json(brand: &BrandFile) -> Result<String, ThemeError> {
    let value = design_tokens(brand)?;
    let mut text = serde_json::to_string_pretty(&value)
        .map_err(|e| ThemeError(format!("cannot encode tokens: {e}")))?;
    text.push('\n');
    Ok(text)
}
