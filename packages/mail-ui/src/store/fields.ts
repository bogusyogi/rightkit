const CUSTOM_SETTER_NAMES: Partial<Record<keyof AppFields, string>> = {
  imagePolicy: "setImagePolicyState",
  signature: "setSignatureState",
  blockTrackers: "setBlockTrackersState",
};

function setterName(key: string): string {
  return `set${key[0].toUpperCase()}${key.slice(1)}`;
}

function makeSetters(fields: AppFields, set: StoreSet) {
  const mk = makeMk(set);
  const setters: Record<string, unknown> = {};
  for (const key of Object.keys(fields) as (keyof AppFields)[]) {
    setters[CUSTOM_SETTER_NAMES[key] ?? setterName(key)] = mk(
      key as keyof AppState,
    );
  }
  return setters;
}

