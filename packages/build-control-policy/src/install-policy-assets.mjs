import { realpathSync } from 'node:fs';
import { resolveManagedRoots } from '../../release/managed-roots.mjs';
import { createHash, randomUUID } from 'node:crypto';
import { copyFile, mkdir, open, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE_FILE, HOOKS, LAUNCH_DIRECTORY, POINTER_FILE, POINTER_SCHEMA } from './hook-launcher.mjs';
const packageRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const files = [
  'ownership-write-hook-cli.mjs',
  'ownership-write-hook.mjs',
  'ownership-source.mjs',
  'ownership-availability.mjs',
  'ownership-session-hook-cli.mjs',
  'ownership-session-hook.mjs',
  'ownership-fingerprints.json',
  'ownership-repositories.json',
  'ownership-dependency-allowlist.mjs',
  'ownership-dependency-allowlist.json',
  'ownership-session-catalog.json',
  'ownership-session-versions.json',
  'rightkit-drift.mjs',
  'background-process.mjs',
].sort();

function rootFor(platform) {
  if (platform === 'win32') return 'D:\\.rightkit-managed\\agent-policy';
  if (platform === 'darwin') return resolveManagedRoots({ platform }).agentPolicy;
  throw new Error(`Unsupported platform: ${platform}`);
}

async function readPolicySnapshot(sourceRoot) {
  const entries = [];
  const hash = createHash('sha256');
  for (const name of files) {
    const bytes = await readFile(join(sourceRoot, 'src', name));
    hash.update(name).update('\0').update(bytes).update('\0');
    entries.push({ name, bytes, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  return { digest: hash.digest('hex'), entries };
}

async function matches(directory, entries) {
  try {
    for (const entry of entries) {
      const bytes = await readFile(join(directory, 'src', entry.name));
      if (!bytes.equals(entry.bytes)) return false;
    }
    return true;
  } catch { return false; }
}

// The launcher directory is the only thing agent hook commands name. Its bytes depend on the launcher source alone,
// never on a policy digest, so a policy activation moves active.json and leaves every registered command untouched.
const stubSource = (hook) => [
  '// RightKit agent-policy hook launcher stub. Generated by install-policy-assets.mjs; its bytes never depend on a policy digest.',
  `import { runHookLauncher } from './${CORE_FILE}';`,
  `await runHookLauncher(${JSON.stringify(hook)});`,
  '',
].join('\n');

async function launcherSnapshot(sourceRoot) {
  const launchers = new Map([[CORE_FILE, await readFile(join(sourceRoot, 'src', CORE_FILE))]]);
  for (const [hook, { launcher }] of Object.entries(HOOKS)) launchers.set(launcher, Buffer.from(stubSource(hook), 'utf8'));
  return launchers;
}

const pointerBytes = (digest) => Buffer.from(`${JSON.stringify({ schemaVersion: POINTER_SCHEMA, digest }, null, 2)}\n`, 'utf8');
const sleep = (ms) => new Promise((done) => setTimeout(done, ms));

// A reader (an agent hook process) can hold the destination open for a moment on Windows.
async function renameReplacing(from, to) {
  for (let attempt = 0; ; attempt += 1) {
    try { return await rename(from, to); }
    catch (error) {
      if (attempt >= 4 || !['EPERM', 'EBUSY', 'EACCES'].includes(error?.code)) throw error;
      await sleep(25 * (attempt + 1));
    }
  }
}

/** Write to a sibling temporary file, flush, then rename over `file`, so readers see the old or the new bytes only. */
async function writeAtomically(file, bytes) {
  const temporary = join(dirname(file), `.${basename(file)}.${process.pid}.${randomUUID()}.tmp`);
  try {
    const handle = await open(temporary, 'wx');
    try { await handle.writeFile(bytes); await handle.sync(); } finally { await handle.close(); }
    await renameReplacing(temporary, file);
  } catch (error) {
    await rm(temporary, { force: true });
    throw error;
  }
}

/** True when `file` was written; an identical file is left alone (no new inode, no new mtime). */
async function writeIfDifferent(file, bytes) {
  try { if ((await readFile(file)).equals(bytes)) return false; }
  catch (error) { if (error?.code !== 'ENOENT') throw error; }
  await writeAtomically(file, bytes);
  return true;
}

/**
 * Install the content-addressed copy, then the stable launchers, then flip active.json to the new digest.
 * `sourceRoot` (a directory holding src/) is a test seam; it defaults to this package.
 */
export async function installPolicyAssets({ root = rootFor(process.platform), sourceRoot = packageRoot } = {}) {
  const { digest, entries } = await readPolicySnapshot(sourceRoot);
  const installRoot = join(root, `content-${digest}`);
  const src = join(installRoot, 'src');
  if (!(await matches(installRoot, entries))) {
    await mkdir(root, { recursive: true });
    const staging = join(root, `.staging-${digest}-${process.pid}`);
    await rm(staging, { recursive: true, force: true });
    await mkdir(join(staging, 'src'), { recursive: true });
    try {
      for (const entry of entries) await copyFile(join(sourceRoot, 'src', entry.name), join(staging, 'src', entry.name));
      await writeFile(join(staging, 'manifest.json'), `${JSON.stringify({
        schema: 'rightkit.agent-policy-assets.v1',
        digest,
        files: entries.map(({ name, sha256 }) => ({ name, sha256 })),
      }, null, 2)}\n`, { flag: 'wx' });
      try { await rename(staging, installRoot); }
      catch (error) {
        if (!(await matches(installRoot, entries))) throw error;
        await rm(staging, { recursive: true, force: true });
      }
    } catch (error) {
      await rm(staging, { recursive: true, force: true });
      throw error;
    }
  }
  const manifest = JSON.parse(await readFile(join(installRoot, 'manifest.json'), 'utf8'));
  if (manifest.digest !== digest || !(await matches(installRoot, entries))) throw new Error(`Installed policy asset digest mismatch: ${installRoot}`);

  // The content copy is complete and verified; only now publish launchers and move the pointer.
  const launchDir = join(root, LAUNCH_DIRECTORY);
  await mkdir(launchDir, { recursive: true });
  const launchers = await launcherSnapshot(sourceRoot);
  const updatedLaunchers = [];
  for (const [name, bytes] of launchers) if (await writeIfDifferent(join(launchDir, name), bytes)) updatedLaunchers.push(name);
  const pointerPath = join(root, POINTER_FILE);
  const pointer = pointerBytes(digest);
  const pointerUpdated = await writeIfDifferent(pointerPath, pointer);
  for (const [name, bytes] of launchers) {
    if (!(await readFile(join(launchDir, name))).equals(bytes)) throw new Error(`Installed launcher mismatch: ${join(launchDir, name)}`);
  }
  if (!(await readFile(pointerPath)).equals(pointer)) throw new Error(`Installed policy pointer mismatch: ${pointerPath}`);
  return Object.freeze({
    digest, root, installRoot, writeHook: join(src, 'ownership-write-hook-cli.mjs'), sessionHook: join(src, 'ownership-session-hook-cli.mjs'),
    launchDir, pointerPath, writeLauncher: join(launchDir, HOOKS.write.launcher), sessionLauncher: join(launchDir, HOOKS.session.launcher),
    updatedLaunchers: Object.freeze(updatedLaunchers), pointerUpdated,
  });
}

const realOrSelf = (file) => { try { return realpathSync(file); } catch { return resolve(file); } };
if (process.argv[1] && realOrSelf(process.argv[1]) === realOrSelf(fileURLToPath(import.meta.url))) {
  const result = await installPolicyAssets();
  process.stdout.write(`${JSON.stringify(result)}\n`);
}
