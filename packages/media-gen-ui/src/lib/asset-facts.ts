// Wording for asset facts and scope, and the search snippet parser. Pure: no React, no engine calls.
// "Not recorded" means the engine holds no fact for this asset. It never reads as a positive claim.
import type { AssetEvidence, AssetFacts, AssetOrigin, AssetRightsStatus, AssetScope } from './types/library.js';

export const NOT_RECORDED = 'Not recorded';

export interface SnippetPart {
  text: string;
  match: boolean;
}

/**
 * Splits an engine prompt_snippet into plain and matched parts. FTS5 marks each match in [brackets].
 * Empty brackets and unmatched brackets stay as plain text, so no characters are dropped.
 */
export function parseSnippet(snippet: string | null | undefined): SnippetPart[] {
  if (!snippet) return [];
  const parts: SnippetPart[] = [];
  const marked = /\[([^[\]]*)\]/g;
  let last = 0;
  let found: RegExpExecArray | null;
  while ((found = marked.exec(snippet)) !== null) {
    if (found.index > last) parts.push({ text: snippet.slice(last, found.index), match: false });
    if (found[1]) parts.push({ text: found[1], match: true });
    else parts.push({ text: found[0], match: false });
    last = marked.lastIndex;
  }
  if (last < snippet.length) parts.push({ text: snippet.slice(last), match: false });
  return parts;
}

function derivedNote(parents: string[] | undefined): string {
  const n = parents?.length ?? 0;
  if (n === 0) return '';
  return n === 1 ? ' · derived from 1 parent asset' : ` · derived from ${n} parent assets`;
}

/** Origin as one line: generated by provider and model, or supplied, acquired or captured, with its source. */
export function originLabel(origin: AssetOrigin | null | undefined): string {
  if (!origin) return NOT_RECORDED;
  const from = origin.source ? ` from ${origin.source}` : '';
  switch (origin.kind) {
    case 'generated':
      return `Generated by ${origin.provider ?? 'provider not recorded'}${origin.model ? ` / ${origin.model}` : ''}${derivedNote(origin.parents)}`;
    case 'supplied':
      return `Supplied${from}`;
    case 'acquired':
      return `Acquired${from}`;
    case 'captured':
      return `Captured${from}`;
    default:
      return NOT_RECORDED;
  }
}

const EVIDENCE_LABEL: Record<AssetEvidence, string> = {
  authentic: 'Authentic',
  illustrative: 'Illustrative',
  unknown: NOT_RECORDED
};

export function evidenceLabel(evidence: string | null | undefined): string {
  return evidence === 'authentic' || evidence === 'illustrative' ? EVIDENCE_LABEL[evidence] : NOT_RECORDED;
}

const RIGHTS_LABEL: Record<AssetRightsStatus, string> = {
  cleared: 'Cleared',
  unresolved: 'Unresolved',
  unknown: NOT_RECORDED
};

export function rightsLabel(status: string | null | undefined): string {
  return status === 'cleared' || status === 'unresolved' ? RIGHTS_LABEL[status] : NOT_RECORDED;
}

/** Venture / channel / account as one line, or "Not recorded" when the asset has no scope. */
export function scopeLabel(scope: AssetScope | null | undefined): string {
  if (!scope) return NOT_RECORDED;
  return `${scope.venture} / ${scope.channel} / ${scope.account}`;
}

/** Label and value rows for an inspector's key-value list. Rows for absent rights detail are left out. */
export function factsRows(facts: AssetFacts | null | undefined, scope: AssetScope | null | undefined): Array<[string, string]> {
  const rows: Array<[string, string]> = [
    ['Origin', originLabel(facts?.origin)],
    ['Evidence', evidenceLabel(facts?.evidence)],
    ['Rights', rightsLabel(facts?.rights?.status)]
  ];
  const rights = facts?.rights;
  if (rights?.licence_evidence?.length) rows.push(['Licence evidence', rights.licence_evidence.join('; ')]);
  if (rights?.attribution) rows.push(['Attribution', rights.attribution]);
  if (rights?.permitted_uses?.length) rows.push(['Permitted uses', rights.permitted_uses.join('; ')]);
  if (rights?.consent_refs?.length) rows.push(['Consent references', rights.consent_refs.join('; ')]);
  rows.push(['Scope', scopeLabel(scope)]);
  return rows;
}

/** The origin kind alone, for a compact chip: Generated, Supplied, Acquired, Captured, or not recorded. */
export function originKindLabel(origin: AssetOrigin | null | undefined): string {
  switch (origin?.kind) {
    case 'generated':
      return 'Generated';
    case 'supplied':
      return 'Supplied';
    case 'acquired':
      return 'Acquired';
    case 'captured':
      return 'Captured';
    default:
      return NOT_RECORDED;
  }
}

const NOT_INDEXED_LABEL: Record<string, string> = {
  transcript: 'transcripts',
  ocr: 'OCR text',
  identity: 'identity',
  embedding: 'embeddings'
};

/** The engine's not_indexed list as a sentence fragment: "transcripts, OCR text, identity, embeddings". */
export function notIndexedText(names: readonly string[]): string {
  return names.map((name) => NOT_INDEXED_LABEL[name] ?? name).join(', ');
}
