import test from 'node:test';
import assert from 'node:assert/strict';
import {
  NOT_RECORDED,
  evidenceLabel,
  factsRows,
  notIndexedText,
  originKindLabel,
  originLabel,
  parseSnippet,
  rightsLabel,
  scopeLabel
} from '../lib/asset-facts.ts';

const unknownFacts = {
  origin: { kind: 'unknown', provider: null, model: null, job_id: null, source: null, parents: [] },
  evidence: 'unknown',
  rights: { status: 'unknown', licence_evidence: [], source: null, attribution: null, permitted_uses: [], consent_refs: [] }
};

test('engine brackets mark matches; the text between them is kept whole', () => {
  assert.deepEqual(parseSnippet('a [chem]ist and [chem]'), [
    { text: 'a ', match: false },
    { text: 'chem', match: true },
    { text: 'ist and ', match: false },
    { text: 'chem', match: true }
  ]);
});

test('a snippet without matches is one plain part, and no input is no parts', () => {
  assert.deepEqual(parseSnippet('Harbour at dusk'), [{ text: 'Harbour at dusk', match: false }]);
  assert.deepEqual(parseSnippet(''), []);
  assert.deepEqual(parseSnippet(null), []);
  assert.deepEqual(parseSnippet(undefined), []);
});

test('empty and unclosed brackets stay as plain text, so no character is dropped', () => {
  const input = 'x [] y [open';
  const parts = parseSnippet(input);
  assert.equal(parts.map((p) => p.text).join(''), input);
  assert.ok(parts.every((p) => p.match === false));
});

test('a generated asset names its provider, model and parent count', () => {
  assert.equal(originLabel({ kind: 'generated', provider: 'fal', model: 'flux-2-pro', job_id: null, source: null, parents: ['a', 'b'] }), 'Generated by fal / flux-2-pro · derived from 2 parent assets');
  assert.equal(originLabel({ kind: 'generated', provider: 'fal', model: 'flux-2-pro', job_id: null, source: null, parents: ['a'] }), 'Generated by fal / flux-2-pro · derived from 1 parent asset');
});

test('a generated asset without a recorded provider is not given one', () => {
  assert.equal(originLabel({ kind: 'generated', provider: null, model: null, job_id: null, source: null, parents: [] }), 'Generated by provider not recorded');
});

test('supplied, acquired and captured assets name their source when one is recorded', () => {
  assert.equal(originLabel({ kind: 'supplied', provider: null, model: null, job_id: null, source: '/in/shot.png', parents: [] }), 'Supplied from /in/shot.png');
  assert.equal(originLabel({ kind: 'acquired', provider: null, model: null, job_id: null, source: 'https://example.com/p', parents: [] }), 'Acquired from https://example.com/p');
  assert.equal(originLabel({ kind: 'captured', provider: null, model: null, job_id: null, source: null, parents: [] }), 'Captured');
});

test('an unknown or absent origin reads as not recorded, never as a source', () => {
  assert.equal(originLabel(unknownFacts.origin), NOT_RECORDED);
  assert.equal(originLabel(null), NOT_RECORDED);
  assert.equal(originLabel(undefined), NOT_RECORDED);
  assert.equal(originKindLabel(unknownFacts.origin), NOT_RECORDED);
  assert.equal(originKindLabel({ kind: 'generated' }), 'Generated');
});

test('unknown evidence and rights are never shown as a positive word', () => {
  assert.equal(evidenceLabel('unknown'), NOT_RECORDED);
  assert.equal(evidenceLabel(undefined), NOT_RECORDED);
  assert.equal(evidenceLabel('authentic'), 'Authentic');
  assert.equal(evidenceLabel('illustrative'), 'Illustrative');
  assert.equal(rightsLabel('unknown'), NOT_RECORDED);
  assert.equal(rightsLabel(null), NOT_RECORDED);
  assert.equal(rightsLabel('unresolved'), 'Unresolved');
  assert.equal(rightsLabel('cleared'), 'Cleared');
});

test('scope reads venture, channel and account, or says it is not recorded', () => {
  assert.equal(scopeLabel({ venture: 'orthic', channel: 'cutright-how-to', account: 'main' }), 'orthic / cutright-how-to / main');
  assert.equal(scopeLabel(null), NOT_RECORDED);
  assert.equal(scopeLabel(undefined), NOT_RECORDED);
});

test('an unknown asset lists only Not recorded rows, with no rights detail', () => {
  assert.deepEqual(factsRows(unknownFacts, null), [
    ['Origin', NOT_RECORDED],
    ['Evidence', NOT_RECORDED],
    ['Rights', NOT_RECORDED],
    ['Scope', NOT_RECORDED]
  ]);
});

test('cleared rights show their licence evidence and attribution when present', () => {
  const facts = {
    origin: { kind: 'supplied', provider: null, model: null, job_id: null, source: '/in/photo.png', parents: [] },
    evidence: 'authentic',
    rights: { status: 'cleared', licence_evidence: ['receipt 4417'], source: null, attribution: 'Photo by A. Example', permitted_uses: ['web'], consent_refs: [] }
  };
  const rows = factsRows(facts, { venture: 'orthic', channel: 'cutright-how-to', account: 'main' });
  assert.deepEqual(rows, [
    ['Origin', 'Supplied from /in/photo.png'],
    ['Evidence', 'Authentic'],
    ['Rights', 'Cleared'],
    ['Licence evidence', 'receipt 4417'],
    ['Attribution', 'Photo by A. Example'],
    ['Permitted uses', 'web'],
    ['Scope', 'orthic / cutright-how-to / main']
  ]);
});

test('the engine not_indexed list reads as a plain sentence fragment', () => {
  assert.equal(notIndexedText(['transcript', 'ocr', 'identity', 'embedding']), 'transcripts, OCR text, identity, embeddings');
});
