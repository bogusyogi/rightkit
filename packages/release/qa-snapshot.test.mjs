/**
 * A real-broker host: the isolated real RustRight instance (test-support/real-broker.mjs), a real git repository committed under the test's own root, the gate's
 * real snapshot of that commit under the instance's `snapshots` root, the enrolled pins of THIS instance (its own attestation public key, the runtime's broker digest, the
 * host name the broker signs), and the section the gate builds from them. The client is the installed `rustright`; every launch goes through the one unguarded
 * launcher the harness itself uses, so no stand-in client exists anywhere.
 */
const REAL_FILES = {
  "Cargo.toml": '[workspace]\nmembers = ["crates/a"]\n', "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "a"\nversion = "0.1.0"\n',
  "crates/a/Cargo.toml": '[package]\nname = "a"\nversion = "0.1.0"\n', "crates/a/src/lib.rs": "\n",
  "native/Cargo.toml": '[workspace]\nmembers = []\n[package]\nname = "b"\nversion = "0.1.0"\n', "native/Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "b"\nversion = "0.1.0"\n', "native/src/lib.rs": "\n",
};
const realSpawn = (file, args, options) => realChildProcess.spawnSync(file, args, options);
const REAL_GATE = fileURLToPath(new URL("./bin/rightkit-gate.mjs", import.meta.url));
const gitIn = (cwd, ...args) => { const r = spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], { cwd, encoding: "utf8" }); if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr}`); return r.stdout.trim(); };

/** The enrollment of a started instance, as `rustright-broker --generate-attestation-key` prints it and `doctor --json` reports the runtime (the secret is never read). */
function realPins(rb) {
  const key = JSON.parse(fs.readFileSync(path.join(rb.controlRoot, "attestation", "key.json"), "utf8"));
  const doctor = JSON.parse(rb.run(["doctor", "--json", "--no-scan"], {}).stdout);
  return { host: process.platform === "win32" ? process.env.COMPUTERNAME : os.hostname(), keyId: key.keyId, publicKey: key.publicKey, brokerDigest: doctor.runtime.expectedBrokerDigest };
}

async function realHost(t, name, { files = {}, handle = "own-7" } = {}) {
  const rb = await startRealBroker({ name });
  t.after(() => rb.stop());
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-real-host-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const checkout = path.join(root, "checkout");
  for (const [rel, body] of Object.entries({ ...REAL_FILES, ...files })) { const f = path.join(checkout, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, body); }
  gitIn(checkout, "init", "-q", "-b", "main"); gitIn(checkout, "add", "-A"); gitIn(checkout, "commit", "-q", "-m", "A");
  const sha = gitIn(checkout, "rev-parse", "HEAD"); const tree = gitIn(checkout, "rev-parse", "HEAD^{tree}");
  const snap = syncSnapshot({ checkout, rev: sha, root: path.join(rb.dataRoot, "snapshots") });
  const pins = realPins(rb);
  const ownership = path.join(root, "build-ownership", "owner.json");
  fs.mkdirSync(path.dirname(ownership), { recursive: true });
  fs.writeFileSync(ownership, JSON.stringify({ handle, broker: { submitted: false } }));
  const ownershipEnv = { [OWNERSHIP_ENV]: handle, [OWNERSHIP_FILE_ENV]: ownership };
  const submits = [];
  const sb = {
    controlRoot: rb.controlRoot, commit: { sha, tree }, snapshot: { path: snap.path, expectedTree: tree }, declaredInputs: [], handle, pins,
    markBrokerSubmit: (callHandle) => { submits.push(callHandle); return markCarriedSend({ file: ownership, handle, callHandle }); },
    checkout, outputRoots: brokerOutputRoots({ dataRoot: rb.dataRoot }), platform: process.platform, client: rb.clientPath,
    receiptOf: async (requestId) => receiptSync({ client: rb.clientPath, requestId, env: rb.env, spawn: realSpawn }),
    leaseStatus: ({ handle: asked, waitMs = 0 }) => brokerLeaseState({ snapshot: snap.path, handle: asked, env: rb.env, platform: process.platform, spawn: realSpawn, client: rb.clientPath, waitMs }),
  };
  const callEnv = { ...rb.env, RUSTRIGHT_CALLING_GATE: REAL_GATE, ...ownershipEnv };
  return { rb, root, checkout, sha, tree, snapshot: snap.path, handle, pins, sb, ownership, ownershipEnv, submits, callEnv, owner: () => JSON.parse(fs.readFileSync(ownership, "utf8")), requests: path.join(rb.controlRoot, "snapshot-requests"), outputRoot: brokerOutputRoots({ dataRoot: rb.dataRoot })[0] };
}


/** A snapshot stage's door host: the map names a snapshot and a primary checkout (the door's QA path rules read them); `cwd` is inside the snapshot. */
function snapshotHost(t) {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-qa-")));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const snapshot = path.join(dir, "snapshot"); const checkout = path.join(dir, "checkout");
  fs.mkdirSync(path.join(snapshot, "app"), { recursive: true }); fs.mkdirSync(path.join(checkout, "app"), { recursive: true });
  const mapFile = path.join(dir, "carrier", "map.json");
  fs.mkdirSync(path.dirname(mapFile), { recursive: true });
  fs.writeFileSync(mapFile, JSON.stringify({ schema: SHIM_MAP_SCHEMA, mode: "broker", broker: { snapshot: { path: snapshot }, checkout }, ledgerDir: path.join(dir, "carrier", "ledger"), workspaces: {} }));
  const qa = path.join(dir, "rightkit-qa");
  const cwd = path.join(snapshot, "app");
  return { dir, qa, snapshot, checkout, cwd, mapFile, host: { platform: "darwin", cwd, exists: (p) => p === CLIENT || p === qa, which: (c) => (c === "rustright" ? [CLIENT] : []), env: { PATH: `/managed/agent-bin:${dir}`, [CARRIED_CARGO_MAP_ENV]: mapFile } } };
}

test("a QA step that compiles nothing runs outside the broker: a direct step with the caller's unscrubbed environment, no adapter job, and never the client", { skip: POSIX }, (t) => {
  const s = snapshotHost(t);
  fs.writeFileSync(s.qa, `#!/bin/sh\nprintf '%s|%s|%s' "$HEARDRIGHT_QA_APP_ROOT" "$RIGHTKIT_QA_TIER" "$*"\n`, { mode: 0o755 });
  const args = ["run-tests", "--from-cargo-json", path.join(s.dir, "carrier", "list.json"), "--app", "heardright", "--parallel", "1", "--", "--nocapture"];
  const launch = buildLaunch("rightkit-qa", args, s.host);
  assert.deepEqual(launch, { command: s.qa, args }, "the QA runner itself, by its resolved path");
  assert.notEqual(launch.command, CLIENT);
  assert.notEqual(launch.command, process.execPath);
  assert.equal(Object.hasOwn(launch, "env"), false, "no adapter environment: QA keeps the caller's own");
  assert.deepEqual(buildLaunch("rustright", ["run", "rightkit-qa", "--", ...args], s.host), launch, "the client spelling is the same direct step");
  const ran = spawnSync(launch.command, launch.args, { env: { ...process.env, HEARDRIGHT_QA_APP_ROOT: "/app", RIGHTKIT_QA_TIER: "fast,local-models" }, encoding: "utf8" });
  assert.equal(ran.status, 0);
  assert.equal(ran.stdout, `/app|fast,local-models|${args.join(" ")}`);
  for (const ok of [["journeys", "receipt", "--root", s.cwd], ["run", "--tier", "fast"], ["--all"]]) assert.deepEqual(buildLaunch("rightkit-qa", ok, s.host), { command: s.qa, args: ok }, ok.join(" "));
  // Off the snapshot route the whole run is still one broker job (the client's `run`), as before.
  assert.throws(() => buildLaunch("rightkit-qa", ["run-tests", "--app", "a"], { ...s.host, env: { PATH: "/managed/agent-bin" } }), (e) => e.code === BUILD_LAUNCH_REFUSED && /no uncarried route/.test(e.message), "GB-27: no carrier, no unregistered adapter request");
  assert.equal(Object.hasOwn(buildLaunch("rightkit-qa", ["--all"], { ...s.host, stepEnv: { HEARDRIGHT_QA_APP_ROOT: "/app" } }), "env"), false);
});

test("a QA step that would compile and cannot be carried is refused, naming the build it needs as its own carried step", { skip: POSIX }, (t) => {
  const s = snapshotHost(t);
  const compiles = [
    ["journeys", "run", "--root", s.cwd, "--build"],
    ["journeys", "run", "--from-cargo-json", path.join(s.dir, "l.jsonl")],
    ["run", "--tier", "fast", "--build"],
    ["run", "--build-ui"],
    ["run-tests", "--from-cargo-json", path.join(s.dir, "l.json"), "--build-with", "cargo"],
    ["run-tests", "--app", "x", "--build-with=rustright"],
    ["cargo", "build"],
    ["run", "pnpm", "build"],
  ];
  for (const args of compiles) {
    assert.ok(qaBuildReason(args, { carried: true }), args.join(" "));
    assert.throws(() => buildLaunch("rightkit-qa", args, s.host), (e) => e.code === BUILD_LAUNCH_REFUSED && /rightkit-qa .*compiles nothing/s.test(e.message) && /its own carried build step/.test(e.message), args.join(" "));
    assert.throws(() => buildLaunch("rustright", ["run", "rightkit-qa", "--", ...args], s.host), (e) => e.code === BUILD_LAUNCH_REFUSED, `via the client spelling: ${args.join(" ")}`);
  }
  // GB-79: a plain `journeys run` is no longer refused as a build: the gate carries its build (qa-journeys-prebuilt.mjs, tested in qa-journeys-prebuilt.test.mjs); it is refused only
  // when the installed rightkit-qa does not advertise the capability, naming it.
  assert.throws(() => buildLaunch("rightkit-qa", ["journeys", "run"], { ...s.host, qaPrebuiltCapability: () => false }), /journeys-prebuilt-input/);
  assert.equal(buildLaunch("rightkit-qa", ["journeys", "run"], { ...s.host, qaPrebuiltCapability: () => true }).command, process.execPath);
  assert.ok(qaBuildReason(["run-tests", "--app", "x"]), "without the gate's carried build, a run-tests step with no listing compiles");
  assert.equal(qaBuildReason(["run-tests", "--from-cargo-json", "/l.json", "--", "cargo"]), null, "arguments after -- go to the test binaries");
  assert.equal(qaBuildReason(["run-tests", "--from-cargo-json=/l.json", "--app", "x"]), null);
});

test("--from-cargo-json counts only in flag position: a value that spells it belongs to the option before it, and QA_VALUE_OPTIONS is complete", () => {
  for (const opt of ["--app", "--env", "--cwd", "--root", "--run-id", "--managed-root", "--receipt", "--unset-env", "--qa-config", "--total-timeout-s", "--binary-timeout-s", "--compile-timeout-s"]) {
    assert.equal(hasListing(["run-tests", opt, "--from-cargo-json", "--parallel", "1"]), false, `${opt} consumes --from-cargo-json as its value`);
    assert.ok(qaBuildReason(["run-tests", opt, "--from-cargo-json"]), `${opt} --from-cargo-json is still a build without a real listing`);
    assert.ok(QA_VALUE_OPTIONS.has(opt), `${opt} is a value option`);
  }
  // The generic scan (other commands) agrees.
  assert.equal(hasListing(["other", "--managed-root", "--from-cargo-json"]), false);
  assert.equal(hasListing(["other", "--from-cargo-json", "l.json"]), true);
  assert.equal(hasListing(["run-tests", "--from-cargo-json", "l.json"]), true);
  assert.equal(hasListing(["run-tests", "--app", "x", "--from-cargo-json=l.json"]), true);
  assert.equal(hasListing(["run-tests", "--app", "x", "--", "--from-cargo-json", "l.json"]), false, "after -- it is a test binary's argument");
  // The parser is the CLI's own: unknown flags (cargo's) do not consume a value, so a listing flag after one is a flag.
  assert.equal(hasListing(["run-tests", "--target", "--from-cargo-json", "l.json"]), true);
  assert.deepEqual(parseRunTests(["--app", "x", "-p", "c", "--features", "f", "--parallel=1", "--", "a"]), { own: ["--app", "x", "--parallel=1"], cargo: ["-p", "c", "--features", "f"], testArgs: ["a"], flags: new Map([["--app", ["x"]], ["--parallel", ["1"]]]) });
  assert.throws(() => parseRunTests(["--app"]), /needs a value/);
});

