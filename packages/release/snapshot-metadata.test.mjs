  assert.deepEqual(s.sent.filter((c) => inSnapshot(c) && !c.carried), [], "no root request inside the snapshot");
  const carried = s.sent.filter((c) => c.carried);
  assert.ok(carried.length >= 1, "discovery was a carried request");
  assert.ok(carried.every((c) => c.argv[0] === "metadata" && c.cwd.startsWith(s.repo)), "carried, read-only, from the primary checkout's counterpart");
  // A carried request whose receipt does not verify (a pin that did not sign it) blocks the stage with the discovery message, not a root fallback.
  const other = crypto.generateKeyPairSync("ec", { namedCurve: "P-256" }).publicKey.export({ format: "jwk" });
