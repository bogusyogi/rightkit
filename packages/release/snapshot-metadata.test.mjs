/** A platform other than this process's: the gate does not probe the file system for a client that a simulated host names (it is never launched here: the test's `spawn` is the only launcher). */
const SIMULATED_PLATFORM = process.platform === "darwin" ? "linux" : "darwin";
const DATA_WORKSPACES = {
  "Cargo.toml": '[workspace]\nmembers = ["crates/a"]\n', "crates/a/Cargo.toml": '[package]\nname = "a"\nversion = "0.1.0"\n', "crates/a/src/lib.rs": "\n",
  "native/Cargo.toml": '[workspace]\nmembers = []\n[package]\nname = "b"\nversion = "0.1.0"\n', "native/src/lib.rs": "\n",
};
function dataHost(t) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-data-host-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const checkout = path.join(root, "checkout"); const dataRoot = path.join(root, "data"); const controlRoot = path.join(root, "control");
  const snapshot = path.join(dataRoot, "snapshots", "0123456789abcdef");
  fs.mkdirSync(controlRoot, { recursive: true });
  for (const base of [checkout, snapshot]) for (const [rel, body] of Object.entries(DATA_WORKSPACES)) { const f = path.join(base, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, body); }
  const { publicKey } = crypto.generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = publicKey.export({ format: "jwk" });
  const sec1 = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x, "base64url"), Buffer.from(jwk.y, "base64url")]).toString("hex");
  const pins = { publicKey: sec1, keyId: crypto.createHash("sha256").update(Buffer.from(sec1, "hex")).digest("hex"), host: "host-1", brokerDigest: "b".repeat(64) };
  const handle = "own-7"; const tree = "e".repeat(40); const marks = [];
  const sb = {
    controlRoot, commit: { sha: "c".repeat(40), tree }, snapshot: { path: snapshot, expectedTree: tree }, declaredInputs: [], handle, pins, checkout,
    outputRoots: [path.join(dataRoot, "rightkit-build-control", "ws")], platform: SIMULATED_PLATFORM, client: "/managed/agent-bin/rustright",
    markBrokerSubmit: (callHandle) => { assert.ok(isCallHandleOf(callHandle, handle), `a broker submit is recorded for a carried request's sub-handle <handle>#<id>, not ${JSON.stringify(callHandle ?? null)}`); marks.push(callHandle); return { handle, broker: { submitted: true, handles: [callHandle] } }; },
    receiptOf: async () => { throw new Error("a data test has no broker to ask for a receipt"); },
  };
  return { root, checkout, dataRoot, controlRoot, snapshot, handle, marks, sb };
}


