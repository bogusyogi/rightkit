test("the files a carried deny reads and the database a carried audit reads must exist, be of the right kind and lie outside the live checkout", (t) => {
  const base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-sm-shape-")));
  t.after(() => fs.rmSync(base, { recursive: true, force: true }));
  const checkout = path.join(base, "checkout"); const gateOwned = path.join(base, "gate");
  fs.mkdirSync(path.join(checkout, "db"), { recursive: true }); fs.mkdirSync(path.join(gateOwned, "db"), { recursive: true });
  fs.writeFileSync(path.join(checkout, "deny.toml"), ""); fs.writeFileSync(path.join(gateOwned, "deny.toml"), ""); fs.writeFileSync(path.join(gateOwned, "m.json"), "{}");
  fs.symlinkSync(path.join(checkout, "deny.toml"), path.join(gateOwned, "link.toml"));
  const refusal = (argv) => carriedScanRefusal(argv, { checkout });
  assert.equal(refusal(["deny", "--frozen", "--metadata-path", path.join(gateOwned, "m.json"), "--config", path.join(gateOwned, "deny.toml"), "check"]), null);
  assert.equal(refusal(["audit", "--db", path.join(gateOwned, "db"), "--no-fetch"]), null);
  assert.match(refusal(["deny", "--config", path.join(checkout, "deny.toml"), "check"]), /inside the live checkout/, "the checkout's own deny.toml is never named");
  assert.match(refusal(["deny", "--config", path.join(gateOwned, "link.toml"), "check"]), /inside the live checkout/, "a link into the checkout is the checkout");
  assert.match(refusal(["audit", "--db", path.join(checkout, "db"), "--no-fetch"]), /inside the live checkout/);
  assert.match(refusal(["deny", "--config", path.join(gateOwned, "absent.toml"), "check"]), /does not exist/);
  assert.match(refusal(["deny", "--config", path.join(gateOwned, "db"), "check"]), /not a file/);
  assert.match(refusal(["audit", "--db", path.join(gateOwned, "m.json"), "--no-fetch"]), /not a directory/);
});


/** Hands the production discovery the real client for both the carried request and the uncarried call, and notes every cargo request the client was asked for. */
const recordingSpawn = (sent) => (file, args, options) => { if (args[0] === "cargo") sent.push({ argv: args.slice(1), cwd: options?.cwd ?? null, carried: options?.env?.RUSTRIGHT_SNAPSHOT_REQUEST !== undefined }); return realSpawn(file, args, options); };
/** The ownership hook of a gate that holds the build ownership: the sub-handle shape is asserted, and what was recorded is kept. */
const ownershipHook = (handle, log) => (callHandle) => { assert.ok(isCallHandleOf(callHandle, handle), `a broker submit is recorded for a carried request's sub-handle <handle>#<id>, not ${JSON.stringify(callHandle ?? null)}`); log.push(callHandle); return { handle, broker: { submitted: true, handles: [callHandle] } }; };

test("real broker: [1311] a root request inside the managed snapshot is refused by the real broker; discovery inside the snapshot is carried: units are found, no root request is made, each call has a verified receipt", async (t) => {
  const fx = await realHost(t, "sm-discovery");
  const records = []; const sent = [];
  const spawn = recordingSpawn(sent);
  const carried = snapshotCargoSpawn({ spawn: root, carrySpawn: spawn, cargoCommand: CARGO, snapshotRoot: fx.snapshot, broker: () => fx.sb, env: { ...fx.callEnv }, records });
  // The broker's own rule: a root request (no carrier) inside the snapshot is refused.
  const plain = fx.rb.run(["cargo", "metadata", "--no-deps", "--format-version", "1", "--locked"], { cwd: fx.snapshot });
  assert.notEqual(plain.status, 0); assert.match(plain.stderr, /a root request cannot run inside a managed snapshot/);
  const found = discoverRustWorkspaces({ root: fx.snapshot, spawn: carried, cargoCommand: CARGO, tracked, readFile: (f) => fs.readFileSync(f, "utf8") });
  assert.ok(found.workspaces.some((w) => w.cargoDir === "."), JSON.stringify(found.workspaces.map((w) => w.cargoDir)));
  assert.ok(found.units.some((u) => u.crate === "a"), "the member crate is discovered from the carried metadata");
  assert.deepEqual(sent.filter((c) => !c.carried), [], "the discovery made no uncarried request");
  assert.ok(sent.length >= 1 && sent.every((c) => c.argv[0] === "metadata" && c.argv.includes("--no-deps")));
  const checkout = fs.realpathSync(fx.checkout);
  assert.ok(sent.every((c) => fs.realpathSync(c.cwd) === checkout || fs.realpathSync(c.cwd).startsWith(`${checkout}${path.sep}`)), "each call ran in the primary checkout's counterpart of the snapshot directory");
  // Each call is recorded pending, then verified (the real receipt the gate checked against its pins, with the broker's request id).
  const settled = records.filter((r) => r.status !== "pending");
  assert.ok(settled.length === sent.length && settled.every((r) => r.status === "verified" && typeof r.requestId === "string"), JSON.stringify(records.map((r) => r.status)));
  assert.ok(fx.submits.length >= 1, "the ownership recorded the broker submit");
});

test("real broker: [1311] a carried request without a valid receipt, or a call the broker would not admit, fails discovery and never becomes a root request", async (t) => {
  const fx = await realHost(t, "sm-negative");
  const errors = []; const sent = [];
  const discoverWith = (sb, carrySpawn = recordingSpawn(sent)) => () => discoverRustWorkspaces({ root: fx.snapshot, spawn: snapshotCargoSpawn({ spawn: root, carrySpawn, cargoCommand: CARGO, snapshotRoot: fx.snapshot, broker: () => sb, env: { ...fx.callEnv }, err: (m) => errors.push(m) }), cargoCommand: CARGO, tracked, readFile: (f) => fs.readFileSync(f, "utf8") });
  // A real receipt a hostile transport altered on its way (the signature must catch it), and a receipt checked against a pin that did not sign it.
  const altering = (edit) => (file, args, options) => { const out = realSpawn(file, args, options); if (args[0] !== "status") return out; const doc = JSON.parse(out.stdout); if (doc.receipt) edit(doc.receipt); return { ...out, stdout: JSON.stringify(doc) }; };
  const other = crypto.generateKeyPairSync("ec", { namedCurve: "P-256" }).publicKey.export({ format: "jwk" });
  const otherKey = Buffer.concat([Buffer.from([4]), Buffer.from(other.x, "base64url"), Buffer.from(other.y, "base64url")]).toString("hex");
  const cases = {
    "signed by another key": [{ ...fx.sb, pins: { ...fx.sb.pins, publicKey: otherKey, keyId: crypto.createHash("sha256").update(Buffer.from(otherKey, "hex")).digest("hex") } }, undefined],
    "no provenance": [fx.sb, altering((r) => { delete r.provenance; })],
    "treeAtExit edited after signing": [fx.sb, altering((r) => { r.provenance.payload.snapshotEvidence.snapshot.treeAtExit = "f".repeat(40); })],
    "another ownership handle": [{ ...fx.sb, handle: "someone-else" }, undefined],
  };
  for (const [name, [sb, carrySpawn]] of Object.entries(cases)) assert.throws(discoverWith(sb, carrySpawn), /cargo metadata failed/, name);
  assert.ok(errors.some((m) => /RK_CARGO_BROKER_UNVERIFIED/.test(m)));
  // The real broker refuses the carried submit while admission is paused: a failed discovery, never a root request.
  assert.equal(fx.rb.run(["pause-admission", "--reason", "snapshot metadata test"], {}).status, 0);
  t.after(() => fx.rb.run(["resume-admission"], {}));
  assert.throws(discoverWith(fx.sb), /cargo metadata failed/);
  assert.equal(fx.rb.run(["resume-admission"], {}).status, 0);
  // Not admitted by the broker inside a snapshot (an unlocked fetch or metadata, a package list, a deny or audit of another shape, anything with
  // cargo's own --config or -Z): refused here, before anything is sent.
  const spawn = snapshotCargoSpawn({ spawn: root, carrySpawn: recordingSpawn(sent), cargoCommand: CARGO, snapshotRoot: fx.snapshot, broker: () => fx.sb, env: { ...fx.callEnv } });
  const before = { submits: fx.submits.length, sent: sent.length };
  for (const argv of [["fetch"], ["deny", "check", "--hide-inclusion-graph"], ["metadata"], ["audit"], ["package", "-p", "a", "--list", "--no-verify", "--locked"], ["build", "--locked"], ["metadata", "--no-deps", "--config", "x=y"], ["deny", "--config", "deny.toml", "check"]]) {
    const r = spawn("rustright", [...CARGO.slice(1), ...argv], { cwd: fx.snapshot });
    assert.notEqual(r.status, 0); assert.match(r.stderr, /RK_SNAPSHOT_CARRIED_REFUSED/);
  }
  assert.deepEqual({ submits: fx.submits.length, sent: sent.length }, before, "nothing was sent to the broker, carried or not");
  // No gate named: the carrier is never forged.
  const noGate = snapshotCargoSpawn({ spawn: root, carrySpawn: recordingSpawn(sent), cargoCommand: CARGO, snapshotRoot: fx.snapshot, broker: () => fx.sb, env: { ...fx.callEnv, RUSTRIGHT_CALLING_GATE: "" } });
  assert.notEqual(noGate("rustright", [...CARGO.slice(1), "metadata", "--no-deps", "--format-version", "1", "--locked"], { cwd: fx.snapshot }).status, 0);
});

