test("real broker: negative: a request directory that is a link, and a request file that cannot be made, refuse the call before the broker is asked; a stale request file is not ours and stays, ours never does; the real client rejects every malformed descriptor", { skip: POSIX }, async (t) => {
  const h = await host(t, { name: "cc-carrier" });
  fs.mkdirSync(h.requests, { recursive: true });
  // The reader accepts only a real directory: a link in its place is refused by the gate before anything is written.
  const elsewhere = path.join(h.fx.root, "elsewhere"); fs.mkdirSync(elsewhere);
  fs.rmSync(h.requests, { recursive: true, force: true }); fs.symlinkSync(elsewhere, h.requests);
  const r = h.cargo(["build"]);
  assert.equal(r.status, 101); assert.match(r.stderr, /RK_CARGO_BROKER_CARRIER/);
  assert.deepEqual(h.fx.submits, []); assert.deepEqual(fs.readdirSync(elsewhere), [], "nothing was written through the link");
  fs.rmSync(h.requests); fs.mkdirSync(h.requests);
  // A stale file of an earlier run: the gate never reads or removes it; the call's own request file is removed.
  fs.writeFileSync(path.join(h.requests, "stale.json"), "{}");
  assert.equal(h.cargo(["build"]).status, 0);
  assert.deepEqual(fs.readdirSync(h.requests), ["stale.json"]);
  // The real client enforces the reader's rules (rustright-cli shims.rs snapshot_carrier): a descriptor to a link, to a directory, unknown fields, a path outside snapshot-requests, an oversize descriptor.
  const run = (env, args = ["build"]) => h.fx.rb.run(["cargo", ...args], { cwd: path.join(h.fx.checkout, "crates", "a"), env: { RUSTRIGHT_CALLING_GATE: GATE, ...env } });
  const link = path.join(h.requests, "link.json"); fs.symlinkSync(path.join(h.requests, "stale.json"), link);
  const sha = "0".repeat(64);
  for (const [name, descriptor] of [["a link", { path: link, sha256: sha }], ["a directory", { path: h.requests, sha256: sha }], ["unknown descriptor fields", { path: link, sha256: sha, extra: 1 }], ["a path outside snapshot-requests", { path: path.join(h.fx.root, "x.json"), sha256: sha }]]) {
    const r2 = run({ RUSTRIGHT_SNAPSHOT_REQUEST: JSON.stringify(descriptor), RUSTRIGHT_ATTEST_NONCE: "c".repeat(64) });
    assert.notEqual(r2.status, 0, name); assert.match(r2.stderr, /invalid snapshot request carrier/, name);
  }
  assert.notEqual(run({ RUSTRIGHT_SNAPSHOT_REQUEST: JSON.stringify({ path: link, sha256: sha, pad: "x".repeat(5000) }) }).status, 0, "an oversize descriptor");
  assert.notEqual(run({ RUSTRIGHT_SNAPSHOT_REQUEST: JSON.stringify({ path: link, sha256: sha }) }, ["build", "--manifest-path", "x"]).status, 0, "an attested call with --manifest-path");
});

