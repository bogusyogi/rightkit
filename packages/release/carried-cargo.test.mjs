/**
 * A real-broker host: the isolated real RustRight instance (test-support/real-broker.mjs), a real git repository committed under the test's own root, the gate's
 * real snapshot of that commit under the instance's `snapshots` root, the enrolled pins of THIS instance (its own attestation public key, the runtime's broker digest, the
 * host name the broker signs), and the section the gate builds from them. The client is the installed `rustright`; every launch goes through the one unguarded
 * launcher the harness itself uses, so no stand-in client exists anywhere.
 */
const REAL_FILES = {
  "Cargo.toml": '[workspace]\nmembers = ["crates/a"]\n', "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "a"\nversion = "0.1.0"\n',
  "crates/a/Cargo.toml": '[package]\nname = "a"\nversion = "0.1.0"\n', "crates/a/src/lib.rs": "\n",
  "native/Cargo.toml": '[workspace]\nmembers = []\n[package]\nname = "b"\nversion = "0.1.0"\n', "native/Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "b"\nversion = "0.1.0"\n', "native/src/lib.rs": "\n",
};
const realSpawn = (file, args, options) => realChildProcess.spawnSync(file, args, options);
const REAL_GATE = fileURLToPath(new URL("./bin/rightkit-gate.mjs", import.meta.url));
const gitIn = (cwd, ...args) => { const r = spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], { cwd, encoding: "utf8" }); if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr}`); return r.stdout.trim(); };

/** The enrollment of a started instance, as `rustright-broker --generate-attestation-key` prints it and `doctor --json` reports the runtime (the secret is never read). */
function realPins(rb) {
  const key = JSON.parse(fs.readFileSync(path.join(rb.controlRoot, "attestation", "key.json"), "utf8"));
  const doctor = JSON.parse(rb.run(["doctor", "--json", "--no-scan"], {}).stdout);
  return { host: process.platform === "win32" ? process.env.COMPUTERNAME : os.hostname(), keyId: key.keyId, publicKey: key.publicKey, brokerDigest: doctor.runtime.expectedBrokerDigest };
}

async function realHost(t, name, { files = {}, handle = "own-7" } = {}) {
  const rb = await startRealBroker({ name });
  t.after(() => rb.stop());
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-real-host-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const checkout = path.join(root, "checkout");
  for (const [rel, body] of Object.entries({ ...REAL_FILES, ...files })) { const f = path.join(checkout, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, body); }
  gitIn(checkout, "init", "-q", "-b", "main"); gitIn(checkout, "add", "-A"); gitIn(checkout, "commit", "-q", "-m", "A");
  const sha = gitIn(checkout, "rev-parse", "HEAD"); const tree = gitIn(checkout, "rev-parse", "HEAD^{tree}");
  const snap = syncSnapshot({ checkout, rev: sha, root: path.join(rb.dataRoot, "snapshots") });
  const pins = realPins(rb);
  const ownership = path.join(root, "build-ownership", "owner.json");
  fs.mkdirSync(path.dirname(ownership), { recursive: true });
  fs.writeFileSync(ownership, JSON.stringify({ handle, broker: { submitted: false } }));
  const ownershipEnv = { [OWNERSHIP_ENV]: handle, [OWNERSHIP_FILE_ENV]: ownership };
  const submits = [];
  const sb = {
    controlRoot: rb.controlRoot, commit: { sha, tree }, snapshot: { path: snap.path, expectedTree: tree }, declaredInputs: [], handle, pins,
    markBrokerSubmit: (callHandle) => { submits.push(callHandle); return markCarriedSend({ file: ownership, handle, callHandle }); },
    checkout, outputRoots: brokerOutputRoots({ dataRoot: rb.dataRoot }), platform: process.platform, client: rb.clientPath,
    receiptOf: async (requestId) => receiptSync({ client: rb.clientPath, requestId, env: rb.env, spawn: realSpawn }),
    leaseStatus: ({ handle: asked, waitMs = 0 }) => brokerLeaseState({ snapshot: snap.path, handle: asked, env: rb.env, platform: process.platform, spawn: realSpawn, client: rb.clientPath, waitMs }),
  };
  const callEnv = { ...rb.env, RUSTRIGHT_CALLING_GATE: REAL_GATE, ...ownershipEnv };
  return { rb, root, checkout, sha, tree, snapshot: snap.path, handle, pins, sb, ownership, ownershipEnv, submits, callEnv, owner: () => JSON.parse(fs.readFileSync(ownership, "utf8")), requests: path.join(rb.controlRoot, "snapshot-requests"), outputRoot: brokerOutputRoots({ dataRoot: rb.dataRoot })[0] };
}

/**
 * A data-test host: plain directories and a section built from constructed values (a checkout and a snapshot with two Cargo workspaces, a control root,
 * a freshly generated P-256 pin, an ownership hook that asserts the sub-handle shape). There is no client, no broker and no receipt: a test that uses it
 * hands the production function a `spawn` of its own and asserts what the gate does with the client's words.
 */
/** A platform other than this process's: the gate does not probe the file system for a client that a simulated host names (it is never launched here: the test's `spawn` is the only launcher). */
const SIMULATED_PLATFORM = process.platform === "darwin" ? "linux" : "darwin";
const DATA_WORKSPACES = {
  "Cargo.toml": '[workspace]\nmembers = ["crates/a"]\n', "crates/a/Cargo.toml": '[package]\nname = "a"\nversion = "0.1.0"\n', "crates/a/src/lib.rs": "\n",
  "native/Cargo.toml": '[workspace]\nmembers = []\n[package]\nname = "b"\nversion = "0.1.0"\n', "native/src/lib.rs": "\n",
};
function dataHost(t) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-data-host-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const checkout = path.join(root, "checkout"); const dataRoot = path.join(root, "data"); const controlRoot = path.join(root, "control");
  const snapshot = path.join(dataRoot, "snapshots", "0123456789abcdef");
  fs.mkdirSync(controlRoot, { recursive: true });
  for (const base of [checkout, snapshot]) for (const [rel, body] of Object.entries(DATA_WORKSPACES)) { const f = path.join(base, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, body); }
  const { publicKey } = crypto.generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = publicKey.export({ format: "jwk" });
  const sec1 = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x, "base64url"), Buffer.from(jwk.y, "base64url")]).toString("hex");
  const pins = { publicKey: sec1, keyId: crypto.createHash("sha256").update(Buffer.from(sec1, "hex")).digest("hex"), host: "host-1", brokerDigest: "b".repeat(64) };
  const handle = "own-7"; const tree = "e".repeat(40); const marks = [];
  const sb = {
    controlRoot, commit: { sha: "c".repeat(40), tree }, snapshot: { path: snapshot, expectedTree: tree }, declaredInputs: [], handle, pins, checkout,
    outputRoots: [path.join(dataRoot, "rightkit-build-control", "ws")], platform: SIMULATED_PLATFORM, client: "/managed/agent-bin/rustright",
    markBrokerSubmit: (callHandle) => { assert.ok(isCallHandleOf(callHandle, handle), `a broker submit is recorded for a carried request's sub-handle <handle>#<id>, not ${JSON.stringify(callHandle ?? null)}`); marks.push(callHandle); return { handle, broker: { submitted: true, handles: [callHandle] } }; },
    receiptOf: async () => { throw new Error("a data test has no broker to ask for a receipt"); },
  };
  return { root, checkout, dataRoot, controlRoot, snapshot, handle, marks, sb };
}


/** A real-broker host with the stage's carrier installed (the broker-mode map), and a runner of seam calls through the real client. */
async function host(t, { name = "cc", files = {} } = {}) {
  const fx = await realHost(t, name, { files });
  const checkoutDirs = { ".": fx.checkout, native: path.join(fx.checkout, "native") };
  const installed = installCarrier({ base: fs.mkdtempSync(path.join(fx.root, "carrier-")), snapshotRoot: fx.snapshot, checkoutDirs, section: brokerSection(fx.sb) });
  t.after(() => installed.cleanup());
  const env = { ...fx.callEnv, ...installed.env };
  const cargo = (args, { cwd = path.join(fx.snapshot, "crates", "a"), over = {}, options = {} } = {}) => runCargoSync(args, { cwd, env: { ...env, ...over }, encoding: "utf8", ...options }, { ...SEAM, spawn: realSpawn });
  const entries = () => readLedger(installed.ledgerDir, UNSCOPED);
  return { constants: requestModule, fx, installed, env, cargo, entries, a: path.join(fx.snapshot, "crates", "a"), native: path.join(fx.snapshot, "native"), requests: fx.requests };
}

test("real broker: the seam: a stage's call is one carried request, from the call's directory, with its own nonce, the real signed receipt verified and ledgered, and its output directory is the receipt's", { skip: POSIX }, async (t) => {
  const h = await host(t, { name: "cc-seam" });
  const r = h.cargo(["build", "--locked", "-p", "a"]);
  assert.equal(r.status, 0, r.stderr);
  const { entries, problems } = h.entries();
  assert.deepEqual(problems, []);
  const receipt = await h.fx.sb.receiptOf(entries[0].requestId);
  assert.equal(r.outputDir, receipt.outputDir, "the output directory is the receipt's");
  assert.ok(path.resolve(r.outputDir).startsWith(`${path.resolve(h.fx.outputRoot)}${path.sep}`), "and it is under the broker's managed ws root");
  assert.deepEqual(entries.map((e) => e.argv), [["build", "--locked", "-p", "a"]]);
  assert.deepEqual(entries.map((e) => e.checkoutCwd), [path.join(h.fx.checkout, "crates", "a")], "the client ran in the checkout counterpart of the call's directory, never in the snapshot");
  assert.deepEqual(entries.map((e) => [e.status, e.mode, e.outputDir]), [["verified", "broker", r.outputDir]]);
  assert.match(entries[0].nonce, /^[0-9a-f]{64}$/);
  assert.deepEqual(await h.installed.problems(h.fx.sb), [], "the gate verifies the receipt again itself");
  assert.deepEqual(h.installed.outputDirs(), [r.outputDir]);
  assert.deepEqual(fs.readdirSync(h.requests), [], "the carrier is removed after the call");
  assert.ok(h.fx.submits.length === 1 && isCallHandleOf(h.fx.submits[0], h.fx.handle), "the ownership recorded this call's sub-handle before it was sent");
  // A second call has a fresh nonce and its own request.
  h.cargo(["check"], { cwd: h.native });
  const second = h.entries().entries;
  assert.equal(new Set(second.map((e) => e.nonce)).size, 2); assert.equal(new Set(second.map((e) => e.requestId)).size, 2);
  assert.deepEqual(await h.installed.problems(h.fx.sb), []);
});

