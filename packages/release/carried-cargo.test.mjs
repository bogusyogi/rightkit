test("real broker: negative: a compile the broker signs FAILED is a failed call in the ledger (the client's failing status is the call's) and fails the stage; a paused broker's refusal is the same; no request file is left behind", { skip: POSIX }, async (t) => {
  const h = await host(t, { name: "cc-neg", files: { "crates/a/src/lib.rs": "pub fn broken( {\n" } });
  const failed = h.cargo(["build"]);
  assert.notEqual(failed.status, 0, "the client's own failure status is the call's");
  assert.equal(failed.outputDir, undefined, "no output directory is taken from an unverified call");
  assert.match(failed.stderr, /RK_CARGO_BROKER_UNVERIFIED/);
  // GB-82: a nonzero exit is a signed FAILED (never a signed success), so the call is NOT a verified success: it is ledgered unverified with the broker's signed outcome.
  assert.equal(h.entries().entries.at(-1).status, "unverified");
  assert.match(h.entries().entries.at(-1).message, /the broker signed FAILED \(exit \d+/);
  const paused = h.fx.rb.run(["pause-admission", "--reason", "carried cargo negative test"], {});
  assert.equal(paused.status, 0, paused.stderr);
  t.after(() => h.fx.rb.run(["resume-admission"], {}));
  const refused = h.cargo(["build"]);
  assert.notEqual(refused.status, 0, "a broker that refuses the carrier");
  assert.match(refused.stderr, /RK_CARGO_BROKER_UNVERIFIED/);
  assert.equal(h.entries().entries.at(-1).code, "broker-refused-paused");
  const { problems } = h.entries();
  assert.equal(problems.length, 2, problems.join("\n"));
  assert.equal((await h.installed.problems(h.fx.sb)).length, 2, "the stage's problems name every one");
  assert.deepEqual(fs.readdirSync(h.requests), [], "no request file is left behind, whatever the outcome");
});

test("real broker: negative: a real receipt altered in any way the gate guards against (another argv, commit, tree, pin, host, broker digest, nonce, handle, request, a stripped or edited signature, a diverging copy, an output directory outside the managed root or inside the checkout) is not accepted", { skip: POSIX }, async (t) => {
  const h = await host(t, { name: "cc-tamper" });
  assert.equal(h.cargo(["build", "--locked", "-p", "a"]).status, 0);
  const [entry] = h.entries().entries;
  const sb = h.fx.sb;
  assert.deepEqual(await verifyBrokerLedger([entry], sb), [], "control: the unaltered real receipt verifies");
  const other = crypto.generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = other.publicKey.export({ format: "jwk" });
  const otherKey = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x, "base64url"), Buffer.from(jwk.y, "base64url")]).toString("hex");
  const mutated = (edit) => async (id) => { const copy = structuredClone(await sb.receiptOf(id)); edit(copy); return copy; };
  const cases = {
    "another argv": [{ argv: [...entry.argv, "--other"] }, {}],
    "another commit": [{}, { commit: { sha: "d".repeat(40), tree: sb.commit.tree } }],
    "a snapshot not the commit's tree": [{}, { commit: { sha: sb.commit.sha, tree: "f".repeat(40) }, snapshot: { ...sb.snapshot, expectedTree: "f".repeat(40) } }],
    "unsigned by the pin": [{}, { pins: { ...sb.pins, publicKey: otherKey, keyId: crypto.createHash("sha256").update(Buffer.from(otherKey, "hex")).digest("hex") } }],
    "another host": [{}, { pins: { ...sb.pins, host: "host-2" } }],
    "another broker digest": [{}, { pins: { ...sb.pins, brokerDigest: "a".repeat(64) } }],
    "another nonce": [{ nonce: "9".repeat(64) }, {}],
    "another ownership handle": [{}, { handle: "someone-else" }],
    "another request": [{ requestId: "33333333-3333-4333-8333-333333333333" }, {}],
    "no provenance": [{}, { receiptOf: mutated((r) => { delete r.provenance; }) }],
    "edited after signing": [{}, { receiptOf: mutated((r) => { r.provenance.payload.snapshotEvidence.snapshot.treeAtExit = "f".repeat(40); }) }],
    "a copy that differs from the signed evidence": [{}, { receiptOf: mutated((r) => { r.outputDir = "/tampered"; }) }],
    "a relative output directory": [{}, { receiptOf: mutated((r) => { r.outputDir = "target"; }) }],
    "an output directory outside the managed ws root": [{}, { outputRoots: [path.join(h.fx.root, "elsewhere")] }],
    "an output directory inside the checkout": [{}, { checkout: h.fx.rb.dataRoot }],
  };
  for (const [name, [entryOver, sbOver]] of Object.entries(cases)) {
    const problems = await verifyBrokerLedger([{ ...entry, ...entryOver }], { ...sb, ...sbOver });
    assert.ok(problems.length >= 1, `${name} is refused`);
  }
});

