// Item 7 row 7.04c, the Linux real row (T2, N5 real, N8 real, T5 on L): a REAL cargo builds a binary from the snapshot of a Tauri-shaped commit with its
// output directory pinned to the CHECKOUT's `src-tauri/target` (the 7.09 bound target); the bound target is resolved by the REAL published resolver
// (cargo-target.mjs `resolveTargetRoot`, a real `cargo metadata`); the declared `src-tauri/target/release/<bin>` is then read, and sealed by the real
// `sealRelease` function, from that directory. No `target` exists under the snapshot before or after. Linux with a real cargo on PATH only
// (never a RustRight shim), run with CI=true or RIGHTKIT_TEST_REAL_BROKER=1 so the test broker guard lets the real toolchain run (as door-real-cargo.test.mjs).
import "./test-support/broker-guard.mjs";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";
import { spawnSync } from "./background-process.mjs";
import { resolveTargetRoot } from "./cargo-target.mjs";
import { resolveNativeCargoLayout } from "./native-cargo-layout.mjs";
import { expandWinPackageTarget } from "./package-recipe-targets.mjs";
import { collectPreflight } from "./preflight.mjs";
import { ArtifactPathError, SPLIT_TARGET_UNRESOLVED_CODE, boundTargetsEvidence, resolveArtifactPath, splitArtifactContext } from "./release-artifact-path.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REAL_CARGO = (() => {
  if (process.platform !== "linux") return null;
  if (process.env.CI !== "true" && process.env.RIGHTKIT_TEST_REAL_BROKER !== "1") return null;
  const r = spawnSync("sh", ["-c", "command -v cargo"], { encoding: "utf8" });
  const at = String(r.stdout ?? "").trim();
  return r.status === 0 && at && !at.includes(".rightkit-managed") ? at : null;
})();
const SKIP = REAL_CARGO ? false : "needs Linux with a real cargo on PATH and CI=true (or RIGHTKIT_TEST_REAL_BROKER=1)";
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
const git = (cwd, ...a) => spawnSync("git", a, { cwd, encoding: "utf8" });

const FILES = {
  ".gitignore": "src-tauri/target/\n",
  "src-tauri/Cargo.toml": '[package]\nname = "fixture-bin"\nversion = "0.1.0"\nedition = "2021"\n',
  "src-tauri/Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "fixture-bin"\nversion = "0.1.0"\n',
  "src-tauri/src/main.rs": 'fn main() { println!("fixture"); }\n',
  "README.md": "committed\n",
};

function setup(t) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-art-real-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const repo = path.join(root, "checkout"); fs.mkdirSync(repo);
  git(repo, "init", "-q", "-b", "main"); git(repo, "config", "user.email", "t@t"); git(repo, "config", "user.name", "t");
  for (const [rel, body] of Object.entries(FILES)) { fs.mkdirSync(path.dirname(path.join(repo, rel)), { recursive: true }); fs.writeFileSync(path.join(repo, rel), body); }
  git(repo, "add", "-A"); git(repo, "commit", "-q", "-m", "c");
  const commit = git(repo, "rev-parse", "HEAD").stdout.trim();
  const snapshot = path.join(root, "snapshot"); fs.mkdirSync(snapshot);
  assert.equal(spawnSync("sh", ["-c", `git -C '${repo}' archive ${commit} | tar -x -C '${snapshot}'`]).status, 0);
  const bound = path.join(repo, "src-tauri", "target"); // the checkout's target_directory: where the gate's 7.09 resolution points
  const artifactDir = path.join(root, "managed"); fs.mkdirSync(artifactDir);
  const withTarget = (fn) => { const before = process.env.CARGO_TARGET_DIR; process.env.CARGO_TARGET_DIR = bound; try { return fn(); } finally { if (before === undefined) delete process.env.CARGO_TARGET_DIR; else process.env.CARGO_TARGET_DIR = before; } };
  const env = { RK_GATE_CHECKOUT: repo, RIGHT_RELEASE_ARTIFACT_DIR: artifactDir, CARGO_TARGET_DIR: bound };
  const nativeLayout = resolveNativeCargoLayout({ appRoot: snapshot, config: {} });
  const compile = () => spawnSync(REAL_CARGO, ["build", "--release", "--locked", "--offline", "--manifest-path", path.join(snapshot, "src-tauri", "Cargo.toml")], { cwd: snapshot, env: { ...process.env, CARGO_TARGET_DIR: bound, CARGO_TERM_COLOR: "never" }, encoding: "utf8" });
  return { root, repo, snapshot, bound, artifactDir, env, nativeLayout, withTarget, compile };
}

const buildSource = fs.readFileSync(path.join(HERE, "build-release.mjs"), "utf8").replace(/\r\n/g, "\n");
function sealer(w, copies) {
  const start = buildSource.indexOf("function sealRelease(");
  const end = buildSource.indexOf("\nfunction collectToolVersions", start);
  return runInNewContext(`${buildSource.slice(start, end)}\nsealRelease;`, {
    ...fs, path, process, ArtifactPathError, resolveSplitArtifactPath: resolveArtifactPath, boundTargetsEvidence,
    assertUpdaterSignature: () => {}, isSuiteUpdaterApp: () => false, resolveUpdaterTrust: () => ({}), assertUpdaterKeyId: () => {},
    hashFile: (file) => sha(fs.readFileSync(file)), copyFileSync: (from, to) => { copies.push([from, to]); fs.copyFileSync(from, to); },
    writeJson: (file, value) => fs.writeFileSync(file, JSON.stringify(value)), fail: (message) => { throw new Error(message); },
    resolveArtifactDir: () => w.artifactDir, materializeArtifacts: () => {}, completeArtifactLease: () => {}, retainArtifacts: () => ({ removed: [] }),
    resolveDevtoolsAllowance: () => ({ mode: "denied" }), devtoolsEvidence: (value) => value,
  });
}
const sealOptions = (w, ctx, sealedDir, artifacts) => ({ configRoot: w.snapshot, managedCargoTarget: null, artifactPaths: ctx, nativeLayout: w.nativeLayout, sealedDir, releaseId: "app-1.0.0-aaaaaaaa", platform: "win", commit: "a".repeat(40),
  config: { app: "app", version: "1.0.0", distribution: {} }, target: { artifacts }, inputHashes: {}, toolVersions: {}, cacheKey: "k" });

test("[T2 real] a real cargo builds the snapshot's binary into the checkout's pinned target; the declared src-tauri/target/release/<bin> is bound by a real `cargo metadata`, sealed from there, and the snapshot never holds a target directory", { skip: SKIP }, (t) => {
  const w = setup(t);
  assert.equal(fs.existsSync(path.join(w.snapshot, "src-tauri", "target")), false, "before");
  const built = w.compile();
  assert.equal(built.status, 0, built.stderr);
  const bin = path.join(w.bound, "release", "fixture-bin");
  assert.ok(fs.existsSync(bin), "cargo wrote the checkout-side target");
  // R-T1 through the published resolver, a real cargo metadata of the SNAPSHOT's manifest under the gate's pinned CARGO_TARGET_DIR.
  const ctx = w.withTarget(() => splitArtifactContext({ cwd: w.snapshot, env: w.env, nativeLayout: w.nativeLayout, config: {}, snapshotRoot: w.snapshot }));
  assert.deepEqual(boundTargetsEvidence(ctx), [{ prefix: "src-tauri/target/", manifest: "src-tauri/Cargo.toml", dir: w.bound }]);
  assert.equal(resolveArtifactPath("src-tauri/target/release/fixture-bin", ctx), bin);
  // The recipe mapper, with the real resolver, does not fail as "outside the app" (P3): the bound target is the checkout's.
  const recipe = w.withTarget(() => expandWinPackageTarget({ signed: true, winPackage: { installer: "nsis", productName: "Demo", updater: true, cargoTargetRoot: true }, sign: { prePackageFiles: ["src-tauri/target/x86_64-pc-windows-msvc/release/demo.exe"], files: ["src-tauri/target/x86_64-pc-windows-msvc/release/bundle/nsis/Demo_1.0.0_x64-setup.exe"] } }, { appRoot: w.snapshot, config: {}, env: w.env }));
  assert.equal(recipe.sign.prePackageFiles[0], path.join(w.bound, "x86_64-pc-windows-msvc", "release", "demo.exe"));
  // The real sealRelease reads the bound target.
  const copies = [];
  sealer(w, copies)(sealOptions(w, ctx, path.join(w.root, "sealed"), ["src-tauri/target/release/fixture-bin"]));
  assert.deepEqual(copies.map(([from]) => from), [bin]);
  const manifest = JSON.parse(fs.readFileSync(path.join(w.root, "sealed", "release-manifest.json"), "utf8"));
  assert.equal(manifest.files[0].sha256, sha(fs.readFileSync(bin)));
  assert.equal(manifest.boundTargets[0].dir, w.bound);
  assert.equal(fs.existsSync(path.join(w.snapshot, "src-tauri", "target")), false, "after");
});

test("[T5 on L] the absolute form postright and cutright compute (resolveTargetRoot of the snapshot's manifest) equals the bound target and seals the same bytes", { skip: SKIP }, (t) => {
  const w = setup(t);
  assert.equal(w.compile().status, 0);
  const ctx = w.withTarget(() => splitArtifactContext({ cwd: w.snapshot, env: w.env, nativeLayout: w.nativeLayout, config: {}, snapshotRoot: w.snapshot }));
  const absolute = path.join(w.withTarget(() => resolveTargetRoot(path.join(w.snapshot, "src-tauri", "Cargo.toml"))), "release", "fixture-bin");
  assert.equal(absolute, path.join(ctx.boundTargets[0].dir, "release", "fixture-bin"));
  const copies = [];
  sealer(w, copies)(sealOptions(w, ctx, path.join(w.root, "sealed"), [absolute]));
  assert.deepEqual(copies.map(([from]) => from), [absolute]);
});

test("[N8 real] an unpinned split (cargo's own answer for the snapshot is a target inside it) is RK_SPLIT_TARGET_UNRESOLVED, and the R-T5 preflight refuses a target/ planted in the snapshot", { skip: SKIP }, (t) => {
  const w = setup(t);
  const unpinned = { RK_GATE_CHECKOUT: w.repo, RIGHT_RELEASE_ARTIFACT_DIR: w.artifactDir };
  const before = process.env.CARGO_TARGET_DIR; delete process.env.CARGO_TARGET_DIR;
  try {
    assert.throws(() => splitArtifactContext({ cwd: w.snapshot, env: unpinned, nativeLayout: w.nativeLayout, config: {}, snapshotRoot: w.snapshot }), (error) => error instanceof ArtifactPathError && error.code === SPLIT_TARGET_UNRESOLVED_CODE && /resolves inside the snapshot/.test(error.message));
  } finally { if (before !== undefined) process.env.CARGO_TARGET_DIR = before; }
  const ctx = w.withTarget(() => splitArtifactContext({ cwd: w.snapshot, env: w.env, nativeLayout: w.nativeLayout, config: {}, snapshotRoot: w.snapshot }));
  fs.mkdirSync(path.join(w.snapshot, "src-tauri", "target"), { recursive: true });
  const check = collectPreflight({ platform: "win", appRoot: w.snapshot, repoRoot: w.repo, nativeLayout: w.nativeLayout, splitTargets: ctx, rust: true, bridge: true, env: {} }).find((entry) => entry.name === "split-target");
  assert.notEqual(check.status, "ok"); assert.match(check.detail, /RK_SPLIT_TARGET_PATH/);
});
