/**
 * A real-broker host: the isolated real RustRight instance (test-support/real-broker.mjs), a real git repository committed under the test's own root, the gate's
 * real snapshot of that commit under the instance's `snapshots` root, the enrolled pins of THIS instance (its own attestation public key, the runtime's broker digest, the
 * host name the broker signs), and the section the gate builds from them. The client is the installed `rustright`; every launch goes through the one unguarded
 * launcher the harness itself uses, so no stand-in client exists anywhere.
 */
const REAL_FILES = {
  "Cargo.toml": '[workspace]\nmembers = ["crates/a"]\n', "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "a"\nversion = "0.1.0"\n',
  "crates/a/Cargo.toml": '[package]\nname = "a"\nversion = "0.1.0"\n', "crates/a/src/lib.rs": "\n",
  "native/Cargo.toml": '[workspace]\nmembers = []\n[package]\nname = "b"\nversion = "0.1.0"\n', "native/Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "b"\nversion = "0.1.0"\n', "native/src/lib.rs": "\n",
};
const realSpawn = (file, args, options) => realChildProcess.spawnSync(file, args, options);
const REAL_GATE = fileURLToPath(new URL("./bin/rightkit-gate.mjs", import.meta.url));
const gitIn = (cwd, ...args) => { const r = spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], { cwd, encoding: "utf8" }); if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr}`); return r.stdout.trim(); };

async function realHost(t, name, { files = {}, handle = "own-7" } = {}) {
  const rb = await startRealBroker({ name });
  t.after(() => rb.stop());
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-real-host-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const checkout = path.join(root, "checkout");
  for (const [rel, body] of Object.entries({ ...REAL_FILES, ...files })) { const f = path.join(checkout, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, body); }
  gitIn(checkout, "init", "-q", "-b", "main"); gitIn(checkout, "add", "-A"); gitIn(checkout, "commit", "-q", "-m", "A");
  const sha = gitIn(checkout, "rev-parse", "HEAD"); const tree = gitIn(checkout, "rev-parse", "HEAD^{tree}");
  const snap = syncSnapshot({ checkout, rev: sha, root: path.join(rb.dataRoot, "snapshots") });
  const pins = rb.pins;
  const ownership = path.join(root, "build-ownership", "owner.json");
  fs.mkdirSync(path.dirname(ownership), { recursive: true });
  fs.writeFileSync(ownership, JSON.stringify({ handle, broker: { submitted: false } }));
  const ownershipEnv = { [OWNERSHIP_ENV]: handle, [OWNERSHIP_FILE_ENV]: ownership };
  const submits = [];
  const sb = {
    controlRoot: rb.controlRoot, commit: { sha, tree }, snapshot: { path: snap.path, expectedTree: tree }, declaredInputs: [], handle, pins,
    markBrokerSubmit: (callHandle) => { submits.push(callHandle); return markCarriedSend({ file: ownership, handle, callHandle }); },
    checkout, outputRoots: brokerOutputRoots({ dataRoot: rb.dataRoot }), platform: process.platform, client: rb.clientPath,
    receiptOf: async (requestId) => receiptSync({ client: rb.clientPath, requestId, env: rb.env, spawn: realSpawn }),
    leaseStatus: ({ handle: asked, waitMs = 0 }) => brokerLeaseState({ snapshot: snap.path, handle: asked, env: rb.env, platform: process.platform, spawn: realSpawn, client: rb.clientPath, waitMs }),
  };
  const callEnv = { ...rb.env, RUSTRIGHT_CALLING_GATE: REAL_GATE, ...ownershipEnv };
  return { rb, root, checkout, sha, tree, snapshot: snap.path, handle, pins, sb, ownership, ownershipEnv, submits, callEnv, owner: () => JSON.parse(fs.readFileSync(ownership, "utf8")), requests: path.join(rb.controlRoot, "snapshot-requests"), outputRoot: brokerOutputRoots({ dataRoot: rb.dataRoot })[0] };
}

test("data: [GB-09] the carrier schema and every per-call variable the gate writes are the current spelling", (t) => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-legacy-data-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const controlRoot = path.join(root, "control"); const snapshot = path.join(root, "data", "snapshots", "0123456789abcdef"); const checkout = path.join(root, "checkout");
  for (const d of [controlRoot, snapshot, checkout]) fs.mkdirSync(d, { recursive: true });
  const made = writeSnapshotRequest({ controlRoot, commit: { sha: "c".repeat(40), tree: "e".repeat(40) }, snapshot: { path: snapshot, expectedTree: "e".repeat(40) }, handle: "own-7", primaryCwd: checkout, argv: ["check"], requestIdFile: path.join(root, "r.json") });
  assert.equal(made.carrier.schema, "rustright.snapshot-request/1");
  assert.equal(SNAPSHOT_REQUEST_SCHEMA, "rustright.snapshot-request/1");
  assert.ok(Object.keys(made.env).every((k) => k.startsWith("RUSTRIGHT_")), Object.keys(made.env).join());
  assert.deepEqual(legacyInterfaceNamesIn(made.env), []);
});

test("[GB-09] a legacy interface name in a call's environment is translated to the current one (the current wins) and never sent; gate-internal RIGHTKIT_ names are untouched", () => {
  const out = currentInterfaceEnv({ RIGHTKIT_ATTEST_NONCE: "a", RIGHTKIT_BUILD_BROKER_SOCKET: "/s", RUSTRIGHT_CALLING_GATE: "new", RIGHTKIT_CALLING_GATE: "old", RIGHTKIT_MANAGED_ROOT: "/m", RIGHTKIT_QA_APP_BINARY: "/q", PATH: "/bin" });
  assert.deepEqual(out, { RUSTRIGHT_ATTEST_NONCE: "a", RUSTRIGHT_BUILD_BROKER_SOCKET: "/s", RUSTRIGHT_CALLING_GATE: "new", RIGHTKIT_MANAGED_ROOT: "/m", RIGHTKIT_QA_APP_BINARY: "/q", PATH: "/bin" });
  const same = { PATH: "/bin" };
  assert.equal(currentInterfaceEnv(same), same);
  for (const [legacy, current] of Object.entries(LEGACY_INTERFACE_ENV)) assert.ok(legacy.startsWith("RIGHTKIT_") && current.startsWith("RUSTRIGHT_") && legacy.slice(9) === current.slice(10), legacy);
  // The one client spawn every production call uses.
  const seen = [];
  spawnBrokerClient((file, args, options) => { seen.push(options.env); return { status: 0 }; }, "rustright", ["status", "x"], { env: { RIGHTKIT_ATTEST_NONCE: "a", RIGHTKIT_ADAPTER_ENV: "X", X: "1" } });
  assert.deepEqual(seen[0], { RUSTRIGHT_ATTEST_NONCE: "a", RUSTRIGHT_ADAPTER_ENV: "X", X: "1" });
  // The legacy adapter-env list is not read either: the client with aliases off would not forward it.
  assert.deepEqual(forwardedAdapterEnv({ RIGHTKIT_ADAPTER_ENV: "X", X: "1" }), {});
});

test("[GB-09] the real RustRight client answers a status call the gate sends through spawnBrokerClient with no legacy name on the wire (a legacy name in the caller's environment is translated, never sent)", async (t) => {
  const rb = await startRealBroker({ name: "legacy-aliases" });
  t.after(() => rb.stop());
  const requestId = "00000000-0000-4000-8000-0000000000aa";
  const env = { ...process.env, ...rb.env, RIGHTKIT_ATTEST_NONCE: "a".repeat(64), RIGHTKIT_ADAPTER_ENV: "X" };
  const seen = [];
  const spawn = (file, args, options) => { seen.push(Object.keys(options.env ?? {})); return spawnSync(file, args, options); };
  // The real broker has no such job: the typed refusal comes from the broker itself, through the production reader.
  assert.throws(() => receiptSync({ client: rb.clientPath, requestId, env, spawn }), (e) => e.code === "broker-refused-not-found", "an unknown request id is the broker's own not-found refusal");
  assert.equal(seen.length, 1);
  assert.deepEqual(legacyInterfaceNamesIn(Object.fromEntries(seen[0].map((k) => [k, "1"]))), [], "no legacy-spelled variable reached the client");
});

test("real broker: [GB-09] with the aliases off, a carried cargo call and a carried adapter call both reach the real broker and verify (the gate sends the current spelling only)", async (t) => {
  const fx = await realHost(t, "legacy-carried", { files: { "scripts/ok.mjs": "process.exit(0);\n" } });
  const section = brokerSection(fx.sb);
  const records = [];
  const env = { ...fx.callEnv, RUSTRIGHT_LEGACY_ALIASES: "off", RIGHTKIT_MANAGED_ROOT: "/gate-internal" };
  const cargo = carryBrokerCargo({ words: ["check"], cwd: path.join(fx.snapshot, "crates", "a"), env, section, workspace: fx.snapshot, checkoutWorkspace: fx.checkout, record: (e) => records.push(e), err: () => {}, stdio: "capture", spawn: realSpawn });
  assert.equal(cargo.outcome.status, "verified", cargo.stderr);
  const adapter = carryBrokerAdapter({ adapter: "rightkit-node", words: ["scripts/ok.mjs"], cwd: fx.snapshot, env, section, record: (e) => records.push(e), err: () => {}, stdio: "capture", spawn: realSpawn });
  assert.equal(adapter.outcome.status, "verified", adapter.stderr);
});
