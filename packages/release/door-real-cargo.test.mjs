// Item 7 Q1 positives 2 and 5 (decision 2): the stage-output ledger with a REAL cargo. Linux only, guarded like cargo-target-shim.test.mjs
// REAL_CARGO (a real cargo on PATH, never a RustRight shim). Evidence label: real git, a real snapshot sync into the test's own root, the REAL
// right-release `stage-sidecar` step run as a split child under the real door, and a real `cargo build -v` of the snapshot with its output
// pinned to a target directory outside it. The class A check is stubbed (not under test) and `verifySnapshot` is the real one (item 5 5.09d).
import "./test-support/broker-guard.mjs";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { spawnSync } from "./background-process.mjs";
import { main } from "./bin/rightkit-gate.mjs";

// Linux with a real cargo on PATH (never a RustRight shim): the direct host the ledger rule exists for.
const REAL_CARGO = (() => {
  if (process.platform !== "linux") return null;
  const r = spawnSync("sh", ["-c", "command -v cargo"], { encoding: "utf8" });
  const at = String(r.stdout ?? "").trim();
  return r.status === 0 && at && !at.includes(".rightkit-managed") ? at : null;
})();
const SKIP = REAL_CARGO ? false : "needs Linux with a real cargo on PATH";
const triple = process.arch === "arm64" ? "aarch64-unknown-linux-gnu" : "x86_64-unknown-linux-gnu";
const git = (cwd, ...a) => spawnSync("git", a, { cwd, encoding: "utf8" });

const FILES = {
  ".gitignore": "binaries/\ngen/\n",
  "right-release.config.json": JSON.stringify({ schema: 1, app: "app", version: "1.0.0", sidecars: { stageDir: "binaries", sidecars: [{ kind: "resource", from: "assets/eng.bin", to: `binaries/eng-${triple}` }] } }) + "\n",
  "switches.json": JSON.stringify({ schema: 1, app: "app", switches: [] }) + "\n",
  "Cargo.toml": '[package]\nname = "app"\nversion = "0.1.0"\nedition = "2021"\nbuild = "build.rs"\n',
  "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "app"\nversion = "0.1.0"\n',
  // What a Tauri crate's build script does: requires the staged externalBin, emits rerun-if-changed for it, writes gen/schemas.
  "build.rs": `use std::{fs, path::Path};
fn main() {
    let triple = std::env::var("TARGET").unwrap();
    let side = format!("binaries/eng-{triple}");
    if !Path::new(&side).exists() { panic!("missing sidecar {side}"); }
    println!("cargo:rerun-if-changed={side}");
    fs::create_dir_all("gen/schemas").unwrap();
    fs::write("gen/schemas/x.json", "{}").unwrap();
}
`,
  "src/main.rs": "fn main() {}\n",
  "assets/eng.bin": "engine-bytes\n",
  "README.md": "committed\n",
};

function setup(t) {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rk-real-cargo-")));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const repo = path.join(dir, "repo"); fs.mkdirSync(repo);
  git(repo, "init", "-q", "-b", "main"); git(repo, "config", "user.email", "t@t"); git(repo, "config", "user.name", "t");
  for (const [rel, body] of Object.entries(FILES)) { fs.mkdirSync(path.dirname(path.join(repo, rel)), { recursive: true }); fs.writeFileSync(path.join(repo, rel), body); }
  git(repo, "add", "-A"); git(repo, "commit", "-q", "-m", "c");
  const sha = git(repo, "rev-parse", "HEAD").stdout.trim();
  const snaps = path.join(dir, "snaps"); const target = path.join(dir, "checkout-target");
  const env = { ...process.env, RIGHTKIT_DATA_ROOT: dir, XDG_STATE_HOME: dir, TAURI_ENV_TARGET_TRIPLE: triple };
  delete env.GITHUB_ACTIONS; delete env.RIGHTKIT_BUILD_OWNERSHIP; delete env.RIGHTKIT_BUILD_OWNERSHIP_FILE; delete env.TAURI_CONFIG;
  const spawn = (c, a, opts) => (c === "git" ? spawnSync(c, a, { ...opts, encoding: "utf8" }) : c === "pnpm" && a[0] === "--version" ? { status: 0, stdout: "11.25.0\n", stderr: "" } : { status: 1, stdout: "", stderr: "" });
  const snapshot = () => path.join(snaps, fs.readdirSync(snaps).find((n) => !n.includes(".") && fs.statSync(path.join(snaps, n)).isDirectory()));
  const stages = []; const builds = [];
  const door = async (compile) => {
    const out = []; const err = [];
    const code = await main(["--to", "compile", "--commit", sha], {
      cwd: repo, platform: "linux", snapshotRoot: snaps, env, spawn, out: (m) => out.push(m), err: (m) => err.push(m), appCheck: async () => 0, runCheck: async () => 0,
      readReceipt: () => null, writeReceipt: ({ receipt }) => { stages.push(receipt.stages); }, resolveExecutor: () => ({ kind: "direct", cargo: ["cargo"] }), runCompile: compile,
    });
    return { code, all: [...out, ...err].join("\n"), err: err.join("\n") };
  };
  // A real `cargo build -v` of the snapshot with its output directory pinned outside it (what the wrapper does for a compile).
  const cargoBuild = async () => {
    // The test process runs under the broker guard (test-support/broker-guard.mjs), which refuses a build tool launched from it outside hosted CI: a real cargo is never started from a test process. This row is
    // about what a real cargo does to a snapshot, so the cargo runs in a plain child (the guard is not loaded there: NODE_OPTIONS cleared), exactly as item7-linux.test.mjs runs its real doors.
    const r = spawnSync(process.execPath, ["-e", "const { spawnSync } = require('node:child' + '_process'); const r = spawnSync(process.argv[1], ['build', '-v', '--locked', '--offline'], { stdio: 'inherit' }); process.exit(r.status ?? 1);", REAL_CARGO],
      { cwd: snapshot(), env: { ...process.env, NODE_OPTIONS: "", CARGO_TARGET_DIR: target, CARGO_TERM_COLOR: "never" }, encoding: "utf8" });
    builds.push(r);
    return r.status === 0 ? 0 : 1;
  };
  return { dir, repo, sha, snaps, target, door, snapshot, stages, builds, cargoBuild };
}

test("[Q1 positive 5 / 7.07 real] a real cargo build of the snapshot passes: the sidecar staged by the real stage-sidecar step, its receipt and the build script's gen/schemas are the ledger, and nothing else is in the snapshot", { skip: SKIP }, async (t) => {
  const fx = setup(t);
  const r = await fx.door(fx.cargoBuild);
  assert.equal(r.code, 0, `${r.all}\n${fx.builds.map((b) => b.stderr).join("\n")}`);
  assert.match(fx.builds[0].stderr, /Compiling app v0\.1\.0/, "the crate was really compiled");
  assert.ok(fs.existsSync(path.join(fx.target, "debug")), "cargo wrote the pinned, checkout-side target directory");
  assert.ok(!fs.existsSync(path.join(fx.snapshot(), "target")), "and no target/ in the snapshot");
  const ledger = fx.stages.at(-1).compile.snapshot.ledger;
  assert.deepEqual(ledger.map((e) => [e.path, e.kind]), [[`binaries/eng-${triple}`, "staged"], ["binaries/stage-sidecar.json", "staged"], ["gen/schemas/x.json", "generated"]]);
  assert.equal(fs.readFileSync(path.join(fx.snapshot(), "gen/schemas/x.json"), "utf8"), "{}", "the build script's ignored output is in the snapshot and was admitted");
});

test("[Q1 positive 2 real] a second door run of the same commit: the sync removes the ledger entries, re-staging restores the bytes with the SOURCE mtime, and cargo finds the app crate fresh", { skip: SKIP }, async (t) => {
  const fx = setup(t);
  let r = await fx.door(fx.cargoBuild);
  assert.equal(r.code, 0, `${r.all}\n${fx.builds.at(-1).stderr}`);
  const first = fs.readFileSync(path.join(fx.snapshot(), `binaries/eng-${triple}`), "utf8");
  r = await fx.door(fx.cargoBuild);
  assert.equal(r.code, 0, `${r.all}\n${fx.builds.at(-1).stderr}`);
  assert.match(r.all, /removed=\d+/, "the sync ran again");
  const staged = path.join(fx.snapshot(), `binaries/eng-${triple}`);
  assert.equal(fs.readFileSync(staged, "utf8"), first, "re-staging restored the same bytes");
  // The carried mtime is the source's at Date (millisecond) precision: never newer than the source, and less than a millisecond older (a file system with
  // nanosecond mtimes, ext4 on Linux, shows the sub-millisecond part the Date drops). Cargo then finds the staged file unchanged, asserted below.
  const sourceMs = fs.statSync(path.join(fx.snapshot(), "assets/eng.bin")).mtimeMs;
  const stagedMs = fs.statSync(staged).mtimeMs;
  assert.ok(stagedMs <= sourceMs && sourceMs - stagedMs < 1, `the staged file carries its source's mtime (to the millisecond), so it is not newer than what cargo recorded: staged ${stagedMs}, source ${sourceMs}`);
  const second = fx.builds.at(-1).stderr;
  assert.match(second, /Fresh app v0\.1\.0/, `the app crate is fresh on the second run:\n${second}`);
  assert.doesNotMatch(second, /Compiling app/);
  const ledgers = [...new Set(fx.stages)].map((s) => s.compile.snapshot.ledger.map((e) => e.sha256)); // one stages object per door run
  // The staged sidecar is byte-identical both times; the stage-sidecar receipt beside it records the run (its own timestamps), so only the sidecar is compared.
  assert.deepEqual(ledgers[1].slice(0, 1), ledgers[0].slice(0, 1), "the staged sidecar has the same digest both times");
});

test("[7.07 negative real] a generator that rewrites a TRACKED file voids the stage (BC:133 B12): exit 2, RK_CHECK_ERROR, the result discarded", { skip: SKIP }, async (t) => {
  const fx = setup(t);
  const r = await fx.door(async () => { fs.writeFileSync(path.join(fx.snapshot(), "README.md"), "rewritten by a generator\n"); return 0; });
  assert.equal(r.code, 2, r.all);
  assert.match(r.err, /RK_CHECK_ERROR: \[compile\]/);
  assert.match(r.err, /the result covers no known bytes/);
  assert.equal(fx.stages.at(-1).compile.ok, false);
});
