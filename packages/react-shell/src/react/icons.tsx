export type IconName = keyof typeof ICONS;

export interface IconProps<G extends string = never> extends Omit<SVGProps<SVGSVGElement>, "name" | "ref" | "children"> {
  /** A shared glyph name, or a name from the app's own `glyphs` extension. */
  name: IconName | G;
  /** App glyphs that extend the shared set (editing or product glyphs). They take the same props. */
  glyphs?: Readonly<Record<G, IconShape>>;
  /** Width and height in px. Default 16. */
  size?: number;
  /** Accessible name. Without it the glyph is decorative and hidden from assistive technology. */
  label?: string;
  className?: string;
}

/**
 * The shared base icon. Strokes use `currentColor`, so it follows the text colour and forced-colors modes. An unknown
 * name renders nothing.
 */
export function Icon<G extends string = never>({ name, glyphs, size = 16, label, className, ...rest }: IconProps<G>) {
  const shape: IconShape | undefined = glyphs && name in glyphs ? glyphs[name as G] : (ICONS as Record<string, IconShape>)[name];
  if (!shape) return null;
  const decorative = label === undefined;
  return (
    <svg
      {...rest}
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cx("rk-icon", className)}
      role={decorative ? undefined : "img"}
      aria-label={decorative ? undefined : label}
      aria-hidden={decorative ? true : undefined}
      focusable="false"
    >
      {shape.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs }))}
    </svg>
  );
}
