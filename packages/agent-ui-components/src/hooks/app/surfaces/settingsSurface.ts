// Settings surface — the settings pane prop assembly.
// Pure forwarding into buildSettingsPaneProps; no effects.

import { buildSettingsPaneProps } from "../../../lib/appSurfaceProps";
import { downloadSupportBundle } from "@rightkit/agent-ui-hooks/hooks/app/useAppSessionActions";
import type { PermissionMode } from "@rightkit/agent-ui-core/lib/daemon";
import type { AppSurfaceInputs } from "./types";

export function buildSettingsSurface(
  a: AppSurfaceInputs,
): ReturnType<typeof buildSettingsPaneProps> {
  const {
    config,
    workspaceRoot,
    engineReady,
    settingsTab,
    setSettingsTab,
    selected,
    permissionMode,
    cyclePermissionMode,
    settings,
    settingsDraft,
    settingsDirty,
    settingsConfigStatus,
    settingsConfigPending,
    setSettingsDraft,
    reloadSettingsConfigNow,
    saveSettings,
    discardSettings,
    skillsRuntime,
    pluginsRuntime,
    mcp,
    lsp,
    permissions,
    localModel,
    diagnosticsState,
    execution,
    telegram,
    licenseView,
    licenseActionPending,
    licenseLatestVersion,
    licenseUpdateState,
    licenseError,
    checkLicenseUpdate,
    downloadLicenseUpdate,
    installLicenseUpdate,
    settingsToolsets,
    toolsetDraft,
    toolsetActionPending,
    toolsetError,
    toolGatewaySnapshot,
    runtime,
    runtimeMiddlewarePending,
    runtimeMiddlewareError,
    coreSandboxSettings,
    setCoreSandboxSettings,
    loadDiagnostics,
    loadSettingsToolsets,
    submitSettingsToolset,
    removeSettingsToolset,
    refreshRuntimeMiddleware,
    toggleRuntimeMiddleware,
    pickWorkspace,
    setStatus,
    setToolsetDraft,
  } = a;

  const PERMISSION_CYCLE: PermissionMode[] = ["ask", "accept-edits", "auto-safe", "plan", "bypass"];

  return buildSettingsPaneProps({
    config,
    workspaceRoot,
    engineReady,
    settingsTab,
    setSettingsTab,
    selected,
    permissionMode,
    permissionModeCycle: () => cyclePermissionMode(PERMISSION_CYCLE),
    orchestration: {
      settings,
      settingsDraft,
      settingsDirty,
      settingsConfigStatus,
      settingsConfigPending,
      setSettingsDraft,
      reloadSettingsConfigNow,
      saveSettings,
      discardSettings,
    },
    skills: skillsRuntime,
    pluginsRuntime,
    mcp,
    lsp,
    permissions,
    localModel,
    diagnosticsState,
    execution,
    telegram,
    license: {
      licenseView,
      licenseActionPending,
      licenseLatestVersion,
      licenseUpdateState,
      licenseError,
      checkLicenseUpdate,
      downloadLicenseUpdate,
      installLicenseUpdate,
    },
    settingsToolsets,
    toolsetDraft,
    toolsetActionPending,
    toolsetError,
    toolGatewaySnapshot,
    runtimeMiddlewareSnapshot: runtime.runtimeMiddlewareSnapshot,
    runtimeMiddlewarePending,
    runtimeMiddlewareError,
    coreSandboxSettings,
    setCoreSandboxSettings,
    loadDiagnostics: () => loadDiagnostics(),
    loadSettingsToolsets: () => loadSettingsToolsets(),
    submitSettingsToolset: () => submitSettingsToolset(),
    removeSettingsToolset: (id: string) => removeSettingsToolset(id),
    refreshRuntimeMiddleware: () => refreshRuntimeMiddleware(),
    toggleRuntimeMiddleware: (id: string, enabled: boolean) => toggleRuntimeMiddleware(id, enabled),
    pickWorkspace: async () => {
      await pickWorkspace();
    },
    downloadSupportBundle: () =>
      diagnosticsState.downloadBundle(config, setStatus, downloadSupportBundle),
    setStatus,
    setToolsetDraft,
    // New Session tab wiring — these are forwarded (not re-derived) so the
    // surface stays a pure forwarder. The actual action lives in
    // executionStore; App.tsx reaches it via the sidebar's prior wiring.
    newSessionControls: a.newSessionControls,
    setNewSessionControls: a.setNewSessionControls,
    modelOptions: a.conductorRuntimeModels,
    newSessionBackendRegistry: execution.backendRegistry,
    newSessionWorkspaces: execution.workspaces,
    newSessionWorkspacePending: execution.workspacePending,
    createNewSessionWorkspace: execution.createWorkspace,
    newSessionWorkspaceRoot: workspaceRoot,
  });
}
