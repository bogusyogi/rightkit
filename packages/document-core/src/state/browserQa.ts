function qaDocKey(): keyof typeof qaDocs | null {
  if (typeof window === "undefined") return null;
  const raw = new URLSearchParams(window.location.search).get("doc") ?? "";
  return raw in qaDocs ? (raw as keyof typeof qaDocs) : null;
}

/// Manual-QA-only escape hatch (not used by the automated `qa:functional:browser` suite): loads a
/// real file straight off disk through Vite dev server's `/@fs/` route, keyed by `?doc=corpus&file=
/// <name>` against `VR_CORPUS_DIR` (default `.qa-corpus/`, same env var the Rust corpus harness in
/// `commands/corpus_qa.rs` uses). Lets a real-world PDF corpus be opened and observed (lazy-render,
/// network panel, memory) via the ordinary QA-mode app shell without any native file dialog.
function qaCorpusFileName(): string | null {
  if (typeof window === "undefined") return null;
  const params = new URLSearchParams(window.location.search);
  if (params.get("doc") !== "corpus") return null;
  return params.get("file");
}

function qaCorpusPath(file: string): string {
  return `D:\\${hostAppName()} QA\\corpus\\${file}`;
}

function qaDocxCorpusFileName(): string | null {
  if (typeof window === "undefined") return null;
  const params = new URLSearchParams(window.location.search);
  const file = params.get("file");
  return params.get("doc") === "docx-corpus" && file && /^[^/\\]+\.docx$/.test(file) ? file : null;
}

const QA_DOCX_CORPUS_PREFIX = `D:\\${hostAppName()} QA\\docx-corpus\\`;

export function qaDialogPath(): string {
  const docxCorpusFile = qaDocxCorpusFileName();
  if (docxCorpusFile) return QA_DOCX_CORPUS_PREFIX + docxCorpusFile;
  const corpusFile = qaCorpusFileName();
  if (corpusFile) return qaCorpusPath(corpusFile);
  return qaDocKey() === "md" ? qaDocs.mdMermaid.path : qaDocs[qaDocKey() ?? "md"].path;
}

export function qaInitialOpenPath(): string | null {
  const docxCorpusFile = qaDocxCorpusFileName();
  if (docxCorpusFile) return QA_DOCX_CORPUS_PREFIX + docxCorpusFile;
  const corpusFile = qaCorpusFileName();
  if (corpusFile) return qaCorpusPath(corpusFile);
  const key = qaDocKey();
  return key ? qaDocs[key].path : null;
}

async function bytesToBase64PdfUrl(bytes: ArrayBuffer): Promise<string> {
  const blob = new Blob([bytes], { type: "application/pdf" });
  const reader = new FileReader();
  return new Promise((resolvePromise, reject) => {
    reader.onload = () => resolvePromise(reader.result as string);
    reader.onerror = () => reject(reader.error);
    reader.readAsDataURL(blob);
  });
}

export async function qaDocumentForPath(path: string): Promise<LoadedDocument | null> {
  if (path.startsWith(QA_DOCX_CORPUS_PREFIX)) {
    const file = path.slice(QA_DOCX_CORPUS_PREFIX.length);
    if (!/^[^/\\]+\.docx$/.test(file)) return null;
    const res = await fetch(`/qa-docx-corpus/${encodeURIComponent(file)}`);
    if (!res.ok) return null;
    const bytes = await res.arrayBuffer();
    const content = await new Promise<string>((resolvePromise, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolvePromise(String(reader.result).split(",", 2)[1] ?? "");
      reader.onerror = () => reject(reader.error);
      reader.readAsDataURL(new Blob([bytes]));
    });
    return {
      path,
      displayName: baseName(path),
      format: "docx",
      content,
      encoding: "UTF-8",
      fingerprint: { mtimeMs: 1, size: bytes.byteLength },
    };
  }
  const corpusPrefix = `D:\\${hostAppName()} QA\\corpus\\`;
  if (path.startsWith(corpusPrefix)) {
    const file = path.slice(corpusPrefix.length);
    const dir = import.meta.env.VITE_VR_CORPUS_DIR ?? "/Volumes/D/claude/viewright/.qa-corpus";
    const res = await fetch(`/@fs/${dir}/${encodeURIComponent(file)}`);
    if (!res.ok) return null;
    const bytes = await res.arrayBuffer();
    const format = formatFromPath(path);
    const assetUrl = format === "pdf" ? await bytesToBase64PdfUrl(bytes) : undefined;
    return {
      path,
      displayName: baseName(path),
      format,
      content: format === "pdf" ? "" : new TextDecoder().decode(bytes),
      assetUrl,
      encoding: "UTF-8",
      fingerprint: { mtimeMs: 1, size: bytes.byteLength },
    };
  }
  const doc = Object.values(qaDocs).find((entry) => entry.path === path);
  if (!doc) return null;
  return {
    path: doc.path,
    displayName: baseName(doc.path),
    format: formatFromPath(doc.path),
    content: doc.content,
    assetUrl: doc.assetUrl,
    lastView: doc.lastView,
    viewMeta: doc.viewMeta,
    encoding: "UTF-8",
    fingerprint: { mtimeMs: 1, size: doc.content.length },
  };
}
