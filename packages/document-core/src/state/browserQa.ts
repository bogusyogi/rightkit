// Keep PDF xref offsets intact while exercising URL schemes accepted/rejected by pdf.js.
function qaPdfUriAsset(uri: string): string {
  const original = "https://example.com/from-pdf";
  if (uri.length > original.length) throw new Error("QA PDF URI must fit existing annotation");
  const bytes = atob(QA_LINK_PDF.split(",")[1]);
  return `data:application/pdf;base64,${btoa(bytes.replace(original, uri.padEnd(original.length, " ")))}`;
}

