import { resolveBrand, type BrandFile, type Mode } from "./brand.js";

export type CssFormat = "suite" | "tailwind" | "both";

export interface GenerateOptions {
  format?: CssFormat;
  /** Shown in the generated header, e.g. `assets/brand/brand.json`. */
  source?: string;
}

const DARK_SELECTORS = [':root[data-theme="dark"]'];
const DARK_MEDIA_SELECTOR = ':root:not([data-theme="light"])';

/** CSS custom properties for one mode. Light carries the accent pair that shell.css reads. */
export function modeVars(brand: BrandFile, mode: Mode): Record<string, string> {
  const r = resolveBrand(brand);
  const p = r.palette[mode];
  const vars: Record<string, string> = {};
  if (mode === "light") {
    vars["--rk-brand"] = r.palette.light["brand-action"];
    vars["--rk-brand-dark"] = r.palette.dark["brand-action"];
    if (brand.wordmark) vars["--rk-wordmark"] = brand.wordmark;
  }
  vars["--rk-brand-mark"] = p.brand;
  for (const [key, value] of Object.entries(p)) {
    if (key === "brand" || key === "brand-action") continue;
    vars[`--rk-${key}`] = value;
  }
  for (const [key, value] of Object.entries(r.overrides[mode])) vars[`--${key}`] = value;
  return vars;
}

const block = (selector: string, vars: Record<string, string>, indent = "") =>
  `${indent}${selector} {\n${Object.entries(vars).map(([k, v]) => `${indent}  ${k}: ${v};`).join("\n")}\n${indent}}\n`;

/** Generate the brand stylesheet. Deterministic: same input, same bytes. */
export function generateCss(brand: BrandFile, options: GenerateOptions = {}): string {
  const format = options.format ?? "suite";
  const source = options.source ?? "the brand file";
  const header = `/* Generated by @rightkit/theme from ${source}; edit the brand file, then run \`rightkit-theme generate\`. */\n`;
  const parts: string[] = [header];
  if (format === "suite" || format === "both") {
    parts.push(block(":root", modeVars(brand, "light")));
    const dark = modeVars(brand, "dark");
    parts.push(`@media (prefers-color-scheme: dark) {\n${block(DARK_MEDIA_SELECTOR, dark, "  ")}}\n`);
    for (const selector of DARK_SELECTORS) parts.push(block(selector, dark));
  }
  if (format === "tailwind" || format === "both") {
    parts.push(`@theme {\n${Object.entries(resolveBrand(brand).palette.light).map(([k, v]) => `  --color-${k}: ${v};`).join("\n")}\n}\n`);
  }
  return parts.join("\n");
}
