#!/usr/bin/env node
// Regenerates tools/rightkit/INDEX.md: every crate and npm package with its version,
// one-line description, publish status, and owned capabilities.
// Run: node tools/rightkit/scripts/generate-index.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const field = (toml, key) => toml.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, "m"))?.[1] ?? "";
const owned = (dir) => {
  const file = path.join(dir, "rightkit-ownership.json");
  if (!existsSync(file)) return "";
  const declared = JSON.parse(readFileSync(file, "utf8"));
  return (declared.capabilities ?? []).map((c) => c.capability).join(", ");
};
const readmeLine = (dir) => {
  const file = path.join(dir, "README.md");
  if (!existsSync(file)) return "";
  return readFileSync(file, "utf8").split(String.fromCharCode(10)).map((l) => l.trim()).find((l) => l && !l.startsWith("#") && !l.startsWith("[!") && !l.startsWith("```")) ?? "";
};
const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const crates = [];
for (const name of readdirSync(path.join(root, "crates")).sort()) {
  const dir = path.join(root, "crates", name);
  const manifest = path.join(dir, "Cargo.toml");
  if (!existsSync(manifest)) continue;
  const toml = readFileSync(manifest, "utf8");
  crates.push({
    name: field(toml, "name") || name,
    version: field(toml, "version"),
    description: field(toml, "description") || readmeLine(dir),
    publish: /^publish\s*=\s*false/m.test(toml) ? "private" : "crates.io",
    owns: owned(dir),
  });
}

const packages = [];
for (const name of readdirSync(path.join(root, "packages")).sort()) {
  const dir = path.join(root, "packages", name);
  const manifest = path.join(dir, "package.json");
  if (!existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, "utf8"));
  packages.push({
    name: pkg.name ?? name,
    version: pkg.version ?? "",
    description: pkg.description || readmeLine(dir),
    publish: pkg.private ? "private" : "npm",
    bins: Object.keys(pkg.bin ?? {}).join(", "),
    owns: owned(dir),
  });
}

const lines = [
  "# RightKit index",
  "",
  "Generated by `node tools/rightkit/scripts/generate-index.mjs`; do not hand-edit. Contracts and boundaries: [README.md](README.md), [docs/RIGHTKIT-SHARED-PACKAGES.md](../../docs/RIGHTKIT-SHARED-PACKAGES.md). Ownership enforcement: `right-release ownership`.",
  "",
  `## Rust crates (${crates.length})`,
  "",
  "| Crate | Version | Published | Owns | What it is |",
  "|---|---|---|---|---|",
  ...crates.map((c) => `| \`${c.name}\` | ${c.version} | ${c.publish} | ${cell(c.owns)} | ${cell(c.description)} |`),
  "",
  `## npm packages (${packages.length})`,
  "",
  "| Package | Version | Published | CLI | Owns | What it is |",
  "|---|---|---|---|---|---|",
  ...packages.map((p) => `| \`${p.name}\` | ${p.version} | ${p.publish} | ${cell(p.bins)} | ${cell(p.owns)} | ${cell(p.description)} |`),
  "",
];
writeFileSync(path.join(root, "INDEX.md"), lines.join("\n"));
console.log(`INDEX.md: ${crates.length} crates, ${packages.length} packages`);
