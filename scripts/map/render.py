#!/usr/bin/env python3
"""Render docs/map/rightkit-map.json (scripts/map/extract.py) into docs/map/RIGHTKIT-MAP.md and docs/map/rightkit-map.html.

Run from the repo root: `python3 -I scripts/map/extract.py && python3 -I scripts/map/render.py`.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MAP = os.path.join(ROOT, "docs", "map")


def semver(v):
    """The first version in `v`: x.y.z, or x.y read as x.y.0 (a two-part Cargo requirement)."""
    m = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", str(v or ""))
    return tuple(int(x or 0) for x in m.groups()) if m else None


def pin_status(pin, current):
    """`pin` an app's requirement string(s), `current` RightKit's source version: current | behind | ahead | path | unknown.
    The extractor joins every requirement it found (`=0.3.6,workspace`): a version among them is the pin; only a pin with no
    version at all and a path, link or file source is `path`."""
    parts = [p.strip() for p in str(pin or "").split(",")]
    versioned = [p for p in parts if semver(p) and not any(k in p for k in ("path", "link:", "file:"))]
    if not versioned:
        return "path" if any(k in str(pin) for k in ("path", "workspace", "link:", "file:")) else "unknown"
    pin = versioned[0]
    want, have = semver(pin), semver(current)
    if not want or not have:
        return "unknown"
    return "current" if want == have else ("behind" if want < have else "ahead")


def main():
    d = json.load(open(os.path.join(MAP, "rightkit-map.json"), encoding="utf-8"))
    units = d["units"]
    by = {u["name"]: u for u in units}
    crates = [u for u in units if u["kind"] == "crate"]
    npms = [u for u in units if u["kind"] == "npm"]
    env = d["env"]

    # reverse dependencies (inside RightKit, normal edges)
    rdeps = {u["name"]: set() for u in units}
    for e in d["edges"]:
        if e["to"] in rdeps and e["kind"] in ("normal", "build", "peer", "optional", "undeclared"):
            rdeps[e["to"]].add(e["from"])
    app_pins = {}
    for a in d["apps"]:
        for p in a["deps"]:
            if p["name"] in by:
                app_pins.setdefault(p["name"], {})[a["name"]] = {"pin": p["version"], "status": pin_status(p["version"], by[p["name"]]["version"])}

    # ---------------------------------------------------------- markdown
    L = []
    w = L.append
    w("# RightKit connection map")
    w("")
    w("Generated by `scripts/map/extract.py` (three passes over the source) and `scripts/map/render.py`. The interactive view of the same data is "
      "[`rightkit-map.html`](rightkit-map.html); the raw data is [`rightkit-map.json`](rightkit-map.json). Regenerate both after any change: "
      "`python3 -I scripts/map/extract.py && python3 -I scripts/map/render.py`.")
    w("")
    w("## How it was traced")
    w("")
    w("- **Pass 1, declared:** every `crates/*/Cargo.toml` and `packages/*/package.json`: version, publish, features, every RightKit dependency (normal, dev, build, peer, target-specific), modules, binaries, size, test count.")
    w("- **Pass 2, used:** every source file, comments and string literals removed, scanned for real uses of each RightKit crate (by its library name and by renamed dependencies) and package (imports, requires, and packages run by name), outside and inside tests (`tests/`, `#[cfg(test)] mod` blocks). Compared with pass 1.")
    w("- **Pass 3, runtime contracts:** environment variables read and set (literal names and names held in constants, resolved across the repository), files, sockets and pipes named in code, programs spawned; then the local product apps, for their RightKit pins and the RightKit variables they read.")
    w("")
    w("Each pass was re-run after its false positives were traced to their cause in the source (comments, Rust char and raw strings, library names, renamed "
      "dependencies, nested example projects, `#[cfg(test)]` spans, one-argument `.env(NAME)` reads, error-code tables shaped like environment objects). "
      "Pass 3 role detection is pattern-based: a variable passed through a helper the patterns cannot see shows up as *mentioned*, not as read or set.")
    w("")
    w("## Totals")
    w("")
    w(f"| | count |\n|---|---|\n| Rust crates | {len(crates)} |\n| npm packages | {len(npms)} |\n| RightKit-internal dependency edges (a unit's dev-dependency on itself not counted) | {sum(1 for e in d['edges'] if e['kind'] != 'app-pin' and e['from'] != e['to'])} |\n"
      f"| Product apps scanned | {len(d['apps'])} |\n| App pins on RightKit units | {sum(1 for e in d['edges'] if e['kind'] == 'app-pin')} |\n| Environment variables | {len(env)} |\n"
      f"| ... shared across units | {sum(v['cross_unit'] for v in env.values())} |\n| Named files | {len(d['files'])} |\n| Sockets / pipes | {len(d['sockets'])} |\n| Spawned programs | {len(d['spawns'])} |\n"
      f"| Source lines (crates + packages) | {sum(u['loc'] for u in units):,} |")
    w("")
    w("## Findings")
    w("")
    w("### Dependencies (pass 2 against pass 1)")
    w("")
    any_dep = False
    for u in units:
        rows = []
        for k, label in (("declared_unused", "declared, never used"), ("used_undeclared", "used, not declared"),
                         ("used_only_in_tests_but_normal_dep", "a runtime (normal, build or required peer) dependency used only by tests"), ("unknown_rightkit_refs", "names a RightKit unit that does not exist")):
            if u.get(k):
                rows.append(f"{label}: {', '.join(f'`{x}`' for x in u[k])}")
        if rows:
            any_dep = True
            w(f"- `{u['name']}`: " + "; ".join(rows))
    if not any_dep:
        w("- none")
    nested = [(u["name"], p) for u in units for p in u.get("nested_projects", [])]
    if nested:
        w("- Nested projects scanned apart from their parent: " + ", ".join(f"`{p}` (in `{n}`)" for n, p in nested))
    w("")
    w("### Environment contracts (pass 3)")
    w("")
    sn = sorted(k for k, v in env.items() if v["set_never_read_in_rk"])
    rn = sorted(k for k, v in env.items() if v["read_never_set_in_rk"])
    ao = sorted(k for k, v in env.items() if v.get("read_by_apps_only"))
    w(f"- **Set by RightKit, read by nothing scanned ({len(sn)}):** a hand-off to an app or tool outside the scan, or a dead value. " + ", ".join(f"`{k}`" for k in sn))
    w(f"- **Set by RightKit, read only by product apps ({len(ao)}):** " + (", ".join(f"`{k}`" for k in ao) or "none"))
    w(f"- **Read by RightKit, set by nothing in RightKit ({len(rn)}):** operator or host inputs (paths, keys, tuning knobs); each is a value a run depends on that RightKit itself never provides. " + ", ".join(f"`{k}`" for k in rn))
    w("")
    w("### App pins against RightKit source")
    w("")
    w("| app | pins | current | behind | ahead | path/other |\n|---|---|---|---|---|---|")
    for a in d["apps"]:
        st = [pin_status(p["version"], by[p["name"]]["version"]) for p in a["deps"] if p["name"] in by]
        w(f"| {a['name']} | {len(st)} | {st.count('current')} | {st.count('behind')} | {st.count('ahead')} | {st.count('path') + st.count('unknown')} |")
    w("")
    w("*Behind* means the app pins an older version than RightKit's source has; *ahead* means it pins a version newer than the source (usually a pin to an unpublished bump).")
    w("")
    w("## Shared environment variables")
    w("")
    w("Every variable that more than one unit sets, reads or names. `(test)` after a unit means every one of its sites for that variable is in a test; `github-workflows` is RightKit's own CI: `.github/workflows` and the `scripts/` they run.")
    w("")
    w("| variable | set by | read by | also named by | apps reading |\n|---|---|---|---|---|")
    for k, v in sorted(env.items()):
        if not v["cross_unit"]:
            continue
        others = sorted(set(v.get("mentioned_by", [])) - set(v["setters"]) - set(v["readers"]))
        def who(side):
            return ", ".join(n + (" (test)" if sites and all("(test)" in x for x in sites) else "") for n, sites in side.items())
        w(f"| `{k}` | {who(v['setters']) or '—'} | {who(v['readers']) or '—'} | {', '.join(others) or '—'} | {', '.join(v.get('app_readers', {})) or '—'} |")
    w("")
    w("## Units")
    w("")
    for kind, title in (("crate", "Rust crates"), ("npm", "npm packages")):
        w(f"### {title}")
        w("")
        for u in sorted((x for x in units if x["kind"] == kind), key=lambda x: x["name"]):
            deps = sorted({e["name"] for e in u["deps"] if e["kind"] in ("normal", "build", "peer", "optional") and e["name"] in by and e["name"] != u["name"]})
            dev = sorted({e["name"] for e in u["deps"] if e["kind"] == "dev" and e["name"] in by and e["name"] != u["name"]})
            w(f"#### `{u['name']}` {u['version']}{'' if (u.get('publish', True) is not False and not u.get('private')) else ' (not published)'}")
            w("")
            if u.get("description"):
                w(u["description"])
                w("")
            w(f"- **Depends on:** {', '.join(f'`{x}`' for x in deps) or 'no RightKit unit'}" + (f"; tests also use {', '.join(f'`{x}`' for x in dev)}" if dev else ""))
            w(f"- **Used by:** {', '.join(f'`{x}`' for x in sorted(rdeps[u['name']])) or 'no RightKit unit'}")
            pins = app_pins.get(u["name"], {})
            if pins:
                w("- **Apps:** " + ", ".join(f"{a} `{p['pin']}`{'' if p['status'] in ('current', 'path') else ' (' + p['status'] + ')'}" for a, p in sorted(pins.items())))
            if kind == "crate":
                if u.get("features"):
                    w(f"- **Features:** {', '.join(f'`{f}`' for f in u['features'])}")
                if u.get("modules"):
                    w(f"- **Public modules:** {', '.join(f'`{m}`' for m in u['modules'])}")
                if u.get("bins"):
                    w(f"- **Binaries:** {', '.join(f'`{b}`' for b in u['bins'])}")
            else:
                if u.get("exports"):
                    w(f"- **Exports:** {', '.join(f'`{x}`' for x in u['exports'][:20])}")
                if u.get("bins"):
                    w(f"- **Binaries:** {', '.join(f'`{b}`' for b in u['bins'])}")
            rt = u.get("runtime", {})
            if rt.get("env_read"):
                w(f"- **Reads env:** {', '.join(f'`{x}`' for x in rt['env_read'][:30])}{' …' if len(rt['env_read']) > 30 else ''}")
            if rt.get("env_set"):
                w(f"- **Sets env:** {', '.join(f'`{x}`' for x in rt['env_set'][:30])}{' …' if len(rt['env_set']) > 30 else ''}")
            if rt.get("spawns"):
                w(f"- **Spawns:** {', '.join(f'`{x}`' for x in rt['spawns'][:20])}")
            if rt.get("sockets"):
                w(f"- **Sockets/pipes:** {', '.join(f'`{x}`' for x in rt['sockets'][:10])}")
            w(f"- **Size:** {u['loc']:,} lines in {u['files']} files" + (f", {u['tests']} tests" if kind == "crate" else f", {u['test_files']} test files"))
            w("")
    with open(os.path.join(MAP, "RIGHTKIT-MAP.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")

    # ---------------------------------------------------------- html data (slim)
    nodes = []
    for u in units:
        rt = u.get("runtime", {})
        nodes.append({
            "id": u["name"], "kind": u["kind"], "version": u["version"], "description": u.get("description", ""),
            "published": not (u.get("publish") is False or u.get("private")), "loc": u["loc"], "files": u["files"],
            "tests": u.get("tests", u.get("test_files", 0)), "features": sorted(u.get("features", {}).keys()) if u["kind"] == "crate" else [],
            "modules": u.get("modules", []), "exports": u.get("exports", []), "bins": u.get("bins", []),
            "env_read": rt.get("env_read", []), "env_set": rt.get("env_set", []), "spawns": rt.get("spawns", []), "sockets": rt.get("sockets", []),
            "files_named": rt.get("files", [])[:60],
            "findings": {k: u.get(k, []) for k in ("declared_unused", "used_undeclared", "used_only_in_tests_but_normal_dep", "unknown_rightkit_refs")},
            "dir": u["dir"], "pins": app_pins.get(u["name"], {}),
        })
    for a in d["apps"]:
        nodes.append({"id": a["name"], "kind": "app", "version": "", "description": f"Product app ({len(a['deps'])} RightKit pins)", "published": True,
                      "loc": 0, "files": 0, "tests": 0, "env_read": sorted(a["env_reads"]), "env_set": [], "dir": a["dir"],
                      "pinlist": [{"name": p["name"], "pin": p["version"], "status": pin_status(p["version"], by[p["name"]]["version"]) if p["name"] in by else "unknown"} for p in a["deps"]]})
    links = [{"source": e["from"], "target": e["to"], "kind": e["kind"], "used": e.get("used_sites", 0), "usedNonTest": e.get("used_non_test", 0),
              "optional": e.get("optional", False), "target_cfg": e.get("target"), "version": e.get("version")} for e in d["edges"] if e["from"] != e["to"]]
    envs = [{"name": k, "setters": v["setters"], "readers": v["readers"], "mentioned": v.get("mentioned_by", []), "apps": v.get("app_readers", {}),
             "cross": v["cross_unit"], "readNeverSet": v["read_never_set_in_rk"], "setNeverRead": v["set_never_read_in_rk"]} for k, v in env.items()]
    data = {"nodes": nodes, "links": links, "env": envs, "generated": "scripts/map/extract.py + render.py"}
    tpl = open(os.path.join(os.path.dirname(__file__), "map.template.html"), encoding="utf-8").read()
    html = tpl.replace("/*__DATA__*/null", json.dumps(data, separators=(",", ":")).replace("</", "<\\/"))
    with open(os.path.join(MAP, "rightkit-map.html"), "w", encoding="utf-8") as fh:
        fh.write(html)
    print("wrote docs/map/RIGHTKIT-MAP.md, docs/map/rightkit-map.html", f"({len(nodes)} nodes, {len(links)} links, {len(envs)} env vars)")


if __name__ == "__main__":
    main()
