// Secretless admission of a LOCAL candidate (reviewed-candidate.mjs, source "local"). Trusted verifier code over DATA: the
// candidate's source is read as git blobs, its archives as bytes, its receipts as JSON. Nothing the candidate ships runs.
// Not imported by the credentialed upload job (its sparse checkout omits this file); the verdict reaches that job only
// through the hashed admission artifact that validateLocalAdmission re-checks.
